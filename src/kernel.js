// §338 landing 5 — THE KERNEL INTERFACE: which implementation answers inspect.js'
// geometric primitives.
//
// The JS path (src/exact-mesh.js, behind inspect.js' `Kernel`) is the REFERENCE and
// the default, and a check is written against it alone (§338's first design
// constraint: a new check never needs the compiled kernel). The compiled kernel is
// an optional ACCELERATOR for the primitives that exist, `distance` (landing 5) and
// `intersects` (landing 6), held to the reference bit for bit by
// tools/probe-338-kernel-parity.mjs (G3): since landing 8 the reference is the same
// algorithm, ported operation for operation.
//
//   await useKernel('wasm')            // or 'js'
//   await useKernel('shadow')          // answer with js, and run wasm beside it on
//                                      // every call, tallying any difference
//   kernelStats()                      // the shadow's tally
//
// The module is src/kernel-wasm.js, GENERATED by tools/kernel-build.mjs from
// tools/kernel/kernel.cpp (never edit it). It is imported only when asked for, so
// the page never loads it.

import { tripleKeys } from './exact-mesh.js';

let mode = 'js';
let W = null;           // the instantiated module's exports
let gen = 0;            // the arena's generation: a reset invalidates every handle
const handles = new WeakMap();   // geometry → { gen, h }
let matPtr = 0;
// The arena is reset (every geometry rebuilt on demand) when it passes this many
// bytes. A function of memory only, never of a value: a geometry's triangles and
// tree are a pure function of its buffers, so a rebuild answers identically.
const ARENA_BUDGET = 512 * 1024 * 1024;

export function kernelMode() { return mode; }
// The instantiated module, for instruments only (G3's membership control drives
// geom_family / geom_refit directly); a check never calls it (CLAUDE.md).
export function kernelExports() { return W; }
// The shadow's tally (§338 landings 7–8). src/exact-mesh.js and the kernel are one
// algorithm in one arithmetic, so the only right count of differences is 0; any
// difference is a port defect, and its first few are kept to name it.
const exactStats = { meets: 0, distance: 0, differ: 0, refMs: 0, wasmMs: 0, samples: [] };
export function shadowTallyExact(kind, ref, k, refMs, wasmMs) {
  exactStats[kind]++;
  exactStats.refMs += refMs; exactStats.wasmMs += wasmMs;
  if (!Object.is(ref, k)) { exactStats.differ++; if (exactStats.samples.length < 6) exactStats.samples.push({ kind, ref, kernel: k }); }
}
export function kernelStats() { return { mode, exact: { ...exactStats, samples: [...exactStats.samples] }, trees: { ...treeStats } }; }
// The compiled kernel's trees (§338 landing 11): built fresh, or refitted from a family.
const treeStats = { builds: 0, refits: 0, resets: 0 };

export async function useKernel(name) {
  if (!['js', 'wasm', 'shadow'].includes(name)) throw new Error(`useKernel: unknown kernel '${name}' (js, wasm or shadow)`);
  if (name !== 'js' && !W) {
    const { KERNEL_WASM_BASE64 } = await import('./kernel-wasm.js');
    const bytes = typeof Buffer !== 'undefined' ? Buffer.from(KERNEL_WASM_BASE64, 'base64')
      : Uint8Array.from(atob(KERNEL_WASM_BASE64), (c) => c.charCodeAt(0));
    const { instance } = await WebAssembly.instantiate(bytes, {});
    W = instance.exports;
    resetArena();
  }
  mode = name;
  for (const k of Object.keys(exactStats)) exactStats[k] = k === 'samples' ? [] : 0;
  treeStats.builds = treeStats.refits = treeStats.resets = 0;
  return mode;
}

function resetArena() {
  W.reset();
  treeStats.resets++;
  gen++;
  matPtr = W.alloc(16 * 8);
}

// §338 landing 11 — A FAMILY'S TREE IS REFITTED, not rebuilt: src/exact-mesh.js'
// rule (landing 9) in the compiled kernel. A geometry whose candidate key (exact-mesh's
// own `tripleKeys`: the counts and an order-independent hash of the vertex triples)
// names a family founded in this arena generation is offered to `geom_refit`, which
// checks MEMBERSHIP itself (the same triangle count, every triple an unclaimed slot of
// the family's table) and refits, or answers 0 and the geometry is built fresh. The
// check is the kernel's because the first version ran it here, over two Sets, and cost
// more than the build it saved (§338 landing 11 records it). A reset invalidates every
// family with its handles, so the next geometry of each is built and founds it again.
const families = new Map();   // famKey → { gen, h }
const LEAF = 8;               // kernel.cpp's LEAF: exact-mesh's rule, no family at or under one leaf

function handleFor(geometry) {
  const hit = handles.get(geometry);
  if (hit && hit.gen === gen) return hit.h;
  if (W.heap_used() > ARENA_BUDGET) resetArena();
  const pos = geometry.attributes.position;
  const n = pos.count;
  const idx = geometry.index ? geometry.index.array : null;
  const ntri = idx ? Math.floor(idx.length / 3) : Math.floor(n / 3);
  const famKey = ntri > LEAF ? tripleKeys(idx, n, ntri).famKey : null;
  const pp = W.alloc(n * 12), ip = W.alloc(ntri * 12);
  if (!pp || !ip) throw new Error('kernel: out of memory copying a geometry');
  const f32 = new Float32Array(W.memory.buffer, pp, n * 3);
  if (pos.isInterleavedBufferAttribute || pos.itemSize !== 3) {
    for (let i = 0; i < n; i++) { f32[3 * i] = pos.getX(i); f32[3 * i + 1] = pos.getY(i); f32[3 * i + 2] = pos.getZ(i); }
  } else f32.set(pos.array.subarray(0, n * 3));
  const u32 = new Uint32Array(W.memory.buffer, ip, ntri * 3);
  if (idx) u32.set(idx.subarray(0, ntri * 3)); else for (let i = 0; i < ntri * 3; i++) u32[i] = i;
  const fam = famKey !== null ? families.get(famKey) : undefined;
  let h = fam && fam.gen === gen ? W.geom_refit(fam.h, pp, ip, ntri) : 0;
  if (h) treeStats.refits++;
  else {
    h = W.geom_create(pp, n, ip, ntri);
    if (!h) throw new Error('kernel: out of memory building a geometry');
    treeStats.builds++;
    if (famKey !== null && (!fam || fam.gen !== gen) && W.geom_family(h)) families.set(famKey, { gen, h });
  }
  handles.set(geometry, { gen, h });
  return h;
}

// The compiled distance: geometry A in its frame, B placed by `m` (a Matrix4's
// elements, B's frame → A's), Infinity when no pair is closer than `upper`.
export function wasmDistance(gA, gB, m, upper) {
  for (let attempt = 0; attempt < 2; attempt++) {
    const g0 = gen;
    const hA = handleFor(gA), hB = handleFor(gB);
    if (gen !== g0 && attempt === 0) continue;          // B's build reset the arena under A: build both again
    new Float64Array(W.memory.buffer, matPtr, 16).set(m);
    const d = W.distance(hA, hB, matPtr, upper);
    if (d >= 0) return d;
    resetArena();                                        // the query's scratch did not fit
  }
  throw new Error('kernel: a distance query does not fit the arena');
}

// §338 landing 6 — the compiled boolean: does any triangle of `gA` meet any
// triangle of `gB` placed by `m` (any invertible affine map, B's frame → A's)?
export function wasmIntersects(gA, gB, m) {
  for (let attempt = 0; attempt < 2; attempt++) {
    const g0 = gen;
    const hA = handleFor(gA), hB = handleFor(gB);
    if (gen !== g0 && attempt === 0) continue;
    new Float64Array(W.memory.buffer, matPtr, 16).set(m);
    const r = W.intersects(hA, hB, matPtr);
    if (r >= 0) return r === 1;
    resetArena();
  }
  throw new Error('kernel: an intersection query does not fit the arena');
}
