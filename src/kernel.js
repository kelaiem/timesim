// §338 landing 5 — THE KERNEL INTERFACE: which implementation answers inspect.js'
// geometric primitives.
//
// The JS path (three-mesh-bvh, inside inspect.js) is the REFERENCE and the default,
// and a check is written against it alone (§338's first design constraint: a new
// check never needs the compiled kernel). The compiled kernel is an optional
// ACCELERATOR for primitives that already exist, held to the reference by
// tools/probe-338-kernel-parity.mjs (G3). Today it accelerates one primitive,
// `distance` (the BVH-vs-BVH closest-point query, 55% of the check phase in
// landing 0's profile); every other primitive is the reference's whatever the
// selection.
//
//   await useKernel('wasm')            // or 'js'
//   await useKernel('shadow')          // answer with js, and run wasm beside it on
//                                      // every call, tallying the disagreements
//   kernelStats()                      // the shadow's tally
//
// The module is src/kernel-wasm.js, GENERATED by tools/kernel-build.mjs from
// tools/kernel/kernel.cpp (never edit it). Since landing 6 it also answers
// `intersects`, the boolean triangle–triangle query. It is imported only when asked for, so
// the page never loads it.

let mode = 'js';
let W = null;           // the instantiated module's exports
let gen = 0;            // the arena's generation: a reset invalidates every handle
const handles = new WeakMap();   // geometry → { gen, h }
let matPtr = 0;
// The arena is reset (every geometry rebuilt on demand) when it passes this many
// bytes. A function of memory only, never of a value: a geometry's triangles and
// tree are a pure function of its buffers, so a rebuild answers identically.
const ARENA_BUDGET = 512 * 1024 * 1024;
const stats = { calls: 0, both: 0, maxAbs: 0, maxAt: null, refFalseZero: 0, refAtOrOverBound: 0, kernelOnly: 0, refOnly: 0, wasmMs: 0, refMs: 0, samples: [] };

export function kernelMode() { return mode; }
// §338 landing 6 — the boolean's own tally: where the two answers agree, and
// each way they part (the reference's `true` the exact test refutes is its
// recorded false-positive mode; the other way round would be a kernel miss).
const boolStats = { calls: 0, agree: 0, refOnly: 0, kernelOnly: 0, wasmMs: 0, refMs: 0 };
export function kernelStats() { return { mode, ...stats, bool: { ...boolStats } }; }

export async function useKernel(name) {
  if (!['js', 'wasm', 'shadow'].includes(name)) throw new Error(`useKernel: unknown kernel '${name}' (js, wasm or shadow)`);
  if (name !== 'js' && !W) {
    const { KERNEL_WASM_BASE64 } = await import('./kernel-wasm.js');
    const bytes = typeof Buffer !== 'undefined' ? Buffer.from(KERNEL_WASM_BASE64, 'base64')
      : Uint8Array.from(atob(KERNEL_WASM_BASE64), (c) => c.charCodeAt(0));
    const { instance } = await WebAssembly.instantiate(bytes, {});
    W = instance.exports;
    resetArena();
  }
  mode = name;
  for (const k of Object.keys(stats)) stats[k] = k === 'maxAt' ? null : k === 'samples' ? [] : 0;
  for (const k of Object.keys(boolStats)) boolStats[k] = 0;
  return mode;
}

function resetArena() {
  W.reset();
  gen++;
  matPtr = W.alloc(16 * 8);
}

function handleFor(geometry) {
  const hit = handles.get(geometry);
  if (hit && hit.gen === gen) return hit.h;
  if (W.heap_used() > ARENA_BUDGET) resetArena();
  const pos = geometry.attributes.position;
  const n = pos.count;
  const idx = geometry.index ? geometry.index.array : null;
  const ntri = idx ? Math.floor(idx.length / 3) : Math.floor(n / 3);
  const pp = W.alloc(n * 12), ip = W.alloc(ntri * 12);
  if (!pp || !ip) throw new Error('kernel: out of memory copying a geometry');
  const f32 = new Float32Array(W.memory.buffer, pp, n * 3);
  if (pos.isInterleavedBufferAttribute || pos.itemSize !== 3) {
    for (let i = 0; i < n; i++) { f32[3 * i] = pos.getX(i); f32[3 * i + 1] = pos.getY(i); f32[3 * i + 2] = pos.getZ(i); }
  } else f32.set(pos.array.subarray(0, n * 3));
  const u32 = new Uint32Array(W.memory.buffer, ip, ntri * 3);
  if (idx) u32.set(idx.subarray(0, ntri * 3)); else for (let i = 0; i < ntri * 3; i++) u32[i] = i;
  const h = W.geom_create(pp, n, ip, ntri);
  if (!h) throw new Error('kernel: out of memory building a geometry');
  handles.set(geometry, { gen, h });
  return h;
}

// The compiled distance: geometry A in its frame, B placed by `m` (a Matrix4's
// elements, B's frame → A's), Infinity when no pair is closer than `upper`.
export function wasmDistance(gA, gB, m, upper) {
  for (let attempt = 0; attempt < 2; attempt++) {
    const g0 = gen;
    const hA = handleFor(gA), hB = handleFor(gB);
    if (gen !== g0 && attempt === 0) continue;          // B's build reset the arena under A: build both again
    new Float64Array(W.memory.buffer, matPtr, 16).set(m);
    const d = W.distance(hA, hB, matPtr, upper);
    if (d >= 0) return d;
    resetArena();                                        // the query's scratch did not fit
  }
  throw new Error('kernel: a distance query does not fit the arena');
}

// §338 landing 6 — the compiled boolean: does any triangle of `gA` meet any
// triangle of `gB` placed by `m` (any invertible affine map, B's frame → A's)?
export function wasmIntersects(gA, gB, m) {
  for (let attempt = 0; attempt < 2; attempt++) {
    const g0 = gen;
    const hA = handleFor(gA), hB = handleFor(gB);
    if (gen !== g0 && attempt === 0) continue;
    new Float64Array(W.memory.buffer, matPtr, 16).set(m);
    const r = W.intersects(hA, hB, matPtr);
    if (r >= 0) return r === 1;
    resetArena();
  }
  throw new Error('kernel: an intersection query does not fit the arena');
}

export function shadowTallyBool(gA, gB, m, ref, refMs) {
  const t0 = performance.now();
  const k = wasmIntersects(gA, gB, m);
  boolStats.wasmMs += performance.now() - t0;
  boolStats.refMs += refMs;
  boolStats.calls++;
  if (k === ref) boolStats.agree++;
  else if (ref) boolStats.refOnly++;
  else boolStats.kernelOnly++;
}

// The shadow's tally, beside the reference's answer `ref` for the same call.
// The reference returns, when nothing is under the bound, either null (read as
// Infinity) or a value at or over it (a leaf whose box passed but whose triangles
// did not), so "at or over the bound" is one answer whichever it gave.
export function shadowTally(gA, gB, m, upper, ref, refMs) {
  const t0 = performance.now();
  const k = wasmDistance(gA, gB, m, upper);
  stats.wasmMs += performance.now() - t0;
  stats.refMs += refMs;
  stats.calls++;
  const refUnder = ref < upper, kUnder = k < upper;
  if (!refUnder && Number.isFinite(ref)) stats.refAtOrOverBound++;
  if (refUnder && kUnder) {
    stats.both++;
    if (ref === 0 && k > 0) { stats.refFalseZero++; return; }
    const d = Math.abs(ref - k);
    if (d > stats.maxAbs) { stats.maxAbs = d; stats.maxAt = { ref, kernel: k, upper }; }
  } else if (kUnder) stats.kernelOnly++;
  else if (refUnder) stats.refOnly++;
  if ((refUnder !== kUnder || (ref === 0 && k > 0)) && stats.samples.length < 6) stats.samples.push({ ref, kernel: k, upper, nA: gA.index ? gA.index.count / 3 : gA.attributes.position.count / 3, nB: gB.index ? gB.index.count / 3 : gB.attributes.position.count / 3 });
}
