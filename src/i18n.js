// THE TABLE IS KEYED BY THE ENGLISH SOURCE STRING. The app keeps authoring
// its UI in English exactly as before; t() (and localizeTree(), which walks
// already-built DOM) resolve through this table, and a missing entry falls
// back to English VISIBLY rather than to a blank — the honest failure. The
// German column doubles as the layout stress test (strings run ~30% longer;
// the §53 240 px column is the constraint) and Chinese as the typography one
// (CJK fallback in the system-ui stack, no-space breaking). §116's three add
// a third and a fourth: French is the first locale whose NUMBERS are not
// ASCII-punctuated (fr-FR groups with U+202F), and Traditional Chinese is the
// first code carrying a SCRIPT subtag — which is why the ladder below is
// ordered and asserted rather than merely written down. §208's Arabic is the
// first locale that reads RIGHT-TO-LEFT, which is a property of the DOCUMENT
// rather than of any string: `dir` on the row, written to documentElement
// beside `lang` below, and every page that imports this file inherits both.
//
// Locale resolution, in priority order (§73): ?lang= param (per-load, not
// persisted — a shared link states what the sharer saw without re-deciding
// the viewer's browser), then the Language row's localStorage choice, then
// navigator.language, then English. Resolved ONCE at import: the panel is
// built from this value and a change reloads (the §22 reload-tier precedent —
// live re-rendering every consumer would be a second rendering path to rot).
//
// OUT OF SCOPE by contract: console.warn / boot asserts (dev-facing English),
// persisted state, deep-link params and canonical state values ('Auto',
// preset names, unit names as VALUES — display is translated, state is not),
// and the dial itself (figures, not words). The reconfigure/route TRIAL
// diagnostics quote solver asserts verbatim and stay English with them —
// recorded residue, not an oversight.
const _param = new URLSearchParams(location.search).get('lang');
let _stored = null;
try { _stored = localStorage.getItem('uiLang'); } catch { /* storage may be blocked */ }
// §116 — THE LOCALE REGISTRY. One declaration: the pickers render its faces,
// _norm resolves through its matchers, LANG_TAG reads its tag, TABLES is keyed
// by its codes. It replaced four hand-kept copies of the list (this file, the
// panel's markup and the two static pages) with one, on the ordinary grounds
// that a list copied four times is a list that disagrees with itself.
//
// ARRAY ORDER IS THE RESOLUTION LADDER — first match wins — and that is
// LOAD-BEARING, not incidental: the matchers overlap on purpose (a script
// subtag has to be tested before the bare language it refines), so reordering
// this array silently changes which table a reader gets. The assert below is
// what makes such a reorder loud, because the failure has no other symptom:
// nothing throws, nothing renders blank, the prose is simply in the wrong
// language for that reader.
//
// `face` is DISPLAY and is written in its own language — the one string on the
// page a reader who cannot yet read the UI must still recognize. `code` is a
// VALUE (§73): it travels in ?lang=, in localStorage and in documentElement.lang,
// and is never translated. `dir` is the locale's writing direction and is
// present ONLY where it is not 'ltr' (§208): the document takes it whole —
// the panels' rows mirror, the pages' prose ranges right — while every
// physical position (the chrome bar's corner, the panel's inset) stays put,
// because those are layout facts about the viewport, not about the script.
// `tag` is for NUMBER FORMATTING only, and Arabic's names its digits on
// purpose: 'ar-u-nu-latn' pins Western digits and the '.'/',' marks, where a
// bare 'ar' answers differently per ICU release and 'ar-EG' answers ٣٠٫٠. The
// dial's figures, the explainer's source-form constants and every deep link
// are Western digits already; one screen gets one digit system.
// zh-Hant BEFORE zh is the ordering this array exists to make visible: every
// Traditional tag begins 'zh', so the bare-language row would swallow all of
// them. 简体中文 is the face the Simplified row now carries — 中文 alone stopped
// being a distinguishing name the moment a second Chinese appeared, and the
// VALUE stayed 'zh' so every ?lang=zh link ever shared still resolves.
// §209 — Spanish's tag carries a REGION decision, the way Arabic's carries a
// digit one. The region subtag changes the DECIMAL mark: measured in Chromium
// 141, 'es-ES' formats 30,0 · 0,024 · 18.000 and 'es-MX' / 'es-419' format
// 30.0 · 0.024 · 18,000 — the split runs through the Spanish-speaking world
// roughly by country. One row is one table, and the primer's numbers are
// WRITTEN in that table in one convention (0,024 mm), so the chrome must
// format the same way or one screen would carry two decimal marks. 'es-ES'
// is that convention; a reader from a '.'-decimal country sees 30,0 —
// legible if unfamiliar — and a second row sharing the table is the fix if
// one reports it (unsupported today: TABLES and both LOADERS are keyed by
// code, one file per code). Nothing else in this array begins 'es'.
// §211 — Korean's matcher is ANCHORED, the first row that is: 'kok' (Konkani)
// begins the same two letters, and startsWith would hand a Konkani reader a
// legible Korean page with no error anywhere — §116's failure shape. The
// ladder assert carries the negative row. 'ko-KR' is number-transparent
// (30.0 · 0.024 · 18,000, English's marks — measured in Chromium 141), so
// its tag decides nothing a reader would notice; the locale's real rule is
// LINE-BREAKING, declared in each document's stylesheet as
// html:lang(ko) { word-break: keep-all } — Hangul has CJK glyph metrics and
// Latin word structure, and the default breaks a word between syllables.
export const LOCALES = [
  { code: 'en', face: 'English', tag: 'en-US', match: (v) => v.startsWith('en') },
  { code: 'de', face: 'Deutsch', tag: 'de-DE', match: (v) => v.startsWith('de') },
  { code: 'fr', face: 'Français', tag: 'fr-FR', match: (v) => v.startsWith('fr') },
  { code: 'es', face: 'Español', tag: 'es-ES', match: (v) => v.startsWith('es') },
  { code: 'ko', face: '한국어', tag: 'ko-KR', match: (v) => /^ko(-|$)/.test(v) },
  { code: 'ja', face: '日本語', tag: 'ja-JP', match: (v) => v.startsWith('ja') },
  { code: 'zh-Hant', face: '繁體中文', tag: 'zh-Hant', match: (v) => /^zh-(hant|tw|hk|mo)\b/.test(v) },
  { code: 'zh', face: '简体中文', tag: 'zh-CN', match: (v) => v.startsWith('zh') },
  { code: 'ar', face: 'العربية', tag: 'ar-u-nu-latn', dir: 'rtl', match: (v) => v.startsWith('ar') },
];
const _norm = (v) => {
  if (!v) return null;
  // Underscores because a stored or hand-typed tag may arrive POSIX-style
  // (zh_TW); lowercase because a matcher should not also be a case table.
  v = String(v).toLowerCase().replace(/_/g, '-');
  return LOCALES.find((L) => L.match(v))?.code || null;
};
export const UI_LANG = _norm(_param) || _norm(_stored) || _norm(navigator.language) || 'en';
// BCP 47 tag for number formatting only — never for content negotiation.
const LANG_TAG = LOCALES.find((L) => L.code === UI_LANG).tag;
document.documentElement.lang = UI_LANG; // screen readers pick pronunciation from this
// §208 — the document's direction is the locale's, declared on the same row
// and written in the same breath as `lang`. Set explicitly to 'ltr' for every
// other locale rather than left absent: a reader switching AWAY from Arabic
// must land on a document that says so, not one that inherits whatever the
// markup carried.
export const UI_DIR = LOCALES.find((L) => L.code === UI_LANG).dir || 'ltr';
document.documentElement.dir = UI_DIR;

