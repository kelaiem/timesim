// THE MODEL OF A BOOKLET
export function bookletOf({ lib, gen, cell, mode, built, plan, bom, flagsTable, paper = PAPERS.letter }) {
  const img = imageBox(paper), aspect = img.w / img.h;
  const fl = flagsFor(flagsTable, plan, gen, cell, mode);
  const nameOf = (id) => { const i = packInfo(lib, id); return i?.title ? `${id} (${i.title})` : id; };
  const views = viewSpecs(plan, lib, { aspect, flagSteps: fl.steps });
  const subOf = new Map(plan.subs.map((x) => [x.id, x]));
  const steps = plan.steps.map((st) => {
    const callout = calloutOf(plan, st, bom);
    const marks = [];
    const addsParts = st.parts.length > 0 || (st.unit?.length ?? 0) > 0;
    if (addsParts && !st.flexible) {
      if (fl.status !== 'ok') marks.push({ kind: 'unchecked', text: UNCHECKED_TEXT });
      for (const it of fl.steps[st.n]?.items ?? []) marks.push(it.s === 'flagged' ? { kind: 'flagged', text: flagText(it, nameOf), item: it } : it.s === 'overlap' ? { kind: 'overlap', text: overlapText(it, nameOf), item: it } : it.s === 'turn' ? { kind: 'turn', text: turnText(it), item: it } : { kind: 'two-leg', text: twoLegText(it), item: it });
    }
    if (st.flexible) marks.push({ kind: 'string', text: 'A string is laid by hand, not slid in, so the insertion check does not sweep it.' });
    const analogueNote = st.kind === 'note' && /analogue/i.test(st.text);
    if (st.kind === 'note') marks.push({ kind: st.posed ? 'posed' : analogueNote ? 'analogue' : 'not-in-model', text: st.text });
    for (const nt of st.notes ?? []) if (/analogue/i.test(nt)) marks.push({ kind: 'analogue', text: nt });
    for (const c of callout) if (c.status === 'unofficial') marks.push({ kind: 'unofficial', text: `Part ${c.part} is not yet in the official LDraw library${c.only2026 ? ' and is a gear of the 2026 catalogue only' : ''}.` });
    const turns = (views.get(st.n)?.arrows ?? []).filter((a) => a.type === 'turn');
    const sameAsTitle = st.text?.replace(/\.$/, '') === st.title;
    const body = st.kind === 'note' || st.kind === 'final' || sameAsTitle ? '' : st.text;
    const subRec = st.sub ? subOf.get(st.sub) : null;
    return { n: st.n, kind: st.kind, title: analogueNote ? 'An analogue, not the Swiss lever' : st.title, text: body, notes: (st.notes ?? []).filter((x) => !/analogue/i.test(x)), chapter: st.chapter, sub: st.sub ?? null, places: st.places ?? null,
      statement: st.kind === 'note' ? 'Modelled, not built.' : null, flexible: !!st.flexible, callout, marks, view: views.get(st.n) ?? null, turns: turns.length, adds: addsParts,
      placeN: subRec && subRec.steps[subRec.steps.length - 1] === st.n ? subRec.place : null, subTitle: subRec?.title ?? (st.places ? subOf.get(st.places)?.title : null) ?? null };
  });
  const notes = NOT_IN_MODEL[built.kind] ?? [];
  const honesty = honestyFor(built.kind, bom.lines);
  const subTitle = new Map(plan.subs.map((s) => [s.id, s]));
  return { meta: { gen, cell, mode: mode ?? null, title: built.title, kind: built.kind, key: plan.key, sig: planSig(plan), flags: fl.status, flagsKey: fl.key, steps: plan.steps.length, placements: plan.parts.length, total: bom.total, lines: bom.lines.length,
      chapters: plan.chapters.length, subs: plan.subs.length, posedForces: plan.posedForces },
    steps, chapters: plan.chapters, subs: plan.subs, subTitle, bom, notes, honesty, views, plan, paper };
}

// ---------------------------------------------------------------------------
// THE PAGE FLOW
// Items in reading order; every one carries an estimated height `h` (the page replaces it with the measured
// one) and the flow rules: `newPage` starts a page, `own` fills one alone, `keepNext` stays with what follows.
export function partsRowHeight(line, paper) {
  const c = contentBox(paper), nameW = c.w - 64 - 44 - 124 - 168 - 4 * 10;
  const text = `${line.title ?? ''} ${line.part} ${line.flags.join(' ')} ${line.purchase.id}`;
  return Math.max(68, textLines(text, nameW) * LAYOUT.line + 24) + 6;
}
export function cardHeight(s, paper) {
  const L = LAYOUT, wide = innerWidth(paper);
  if (s.kind === 'note') {
    const nw = wide - 160 - L.gap;                                        // the note's text column, beside its diagram
    const nb = 30 + textLines(`${s.title}. ${s.statement ?? ''}`, nw, L.title, CHAR_EM_BOLD) * L.line + 4 + s.marks.reduce((n, m) => n + textLines(`${m.kind} ${m.text}`, nw) * L.line + MARK_BOX_PX, 0);
    return L.cardPad * 2 + L.cardBorder + Math.max(100, nb) + L.cardGap;
  }
  const rows = Math.ceil(s.callout.length / 2), call = L.numH + rows * L.pipH + Math.max(0, rows - 1) * L.pipGap;
  const media = Math.max(L.imgH, call);
  let body = L.bodyGap + textLines(s.title, wide, L.title, CHAR_EM_BOLD) * L.titleLine;
  body += textLines(s.text, wide) * L.line;
  for (const nt of s.notes) body += textLines(nt, wide) * L.line;
  for (const m of s.marks) body += textLines(`${m.kind} ${m.text}`, wide - 14 - 10) * L.line + MARK_BOX_PX;
  if (s.sub && !s.places) body += L.line;                                // the sub-assembly tag above the title
  if (s.placeN) body += L.line;                                          // "the finished sub-assembly goes into the model in step n"
  return L.cardPad * 2 + L.cardBorder + media + body + L.cardGap;
}
export function layoutItems(model, paper = model.paper) {
  const c = contentBox(paper), items = [];
  items.push({ id: 'cover', type: 'cover', own: true, h: c.h });
  const head = 120 + textLines(model.honesty.join(' '), c.w) * LAYOUT.line;
  items.push({ id: 'parts-head', type: 'parts-head', newPage: true, keepNext: true, h: head });
  for (const [k, line] of model.bom.lines.entries()) items.push({ id: `parts-${k}`, type: 'parts-row', k, h: partsRowHeight(line, paper) });
  const nim = model.notes.reduce((n, x) => n + textLines(`${x.item} ${x.quantity} ${x.why}`, c.w - 20) * LAYOUT.line + 10, 0);
  items.push({ id: 'parts-foot', type: 'parts-foot', h: 60 + nim + model.honesty.reduce((n, t) => n + textLines(t, c.w) * LAYOUT.line, 0) });
  let chap = null, first = true;
  const steps = model.steps.filter((s) => s.kind !== 'final');
  for (const s of steps) {
    if (s.chapter !== chap) {
      chap = s.chapter;
      items.push({ id: `chapter-${chap}`, type: 'chapter', chapter: chap, keepNext: true, newPage: first, h: LAYOUT.chapterH });
      first = false;
    }
    items.push({ id: `step-${s.n}`, type: 'step', n: s.n, h: cardHeight(s, paper) });
  }
  const fin = model.steps.find((s) => s.kind === 'final');
  items.push({ id: 'final', type: 'final', n: fin?.n ?? null, own: true, h: c.h });
  return items;
}
// Greedy flow into pages of `capacity` height. An item taller than a page is reported (`overflow`), not split.
export function paginate(items, capacity) {
  const pages = [], overflow = [];
  let cur = { items: [], used: 0 };
  const flush = () => { if (cur.items.length) pages.push(cur); cur = { items: [], used: 0 }; };
  for (let i = 0; i < items.length; i++) {
    const it = items[i];
    if (it.newPage || it.own) flush();
    if (it.h > capacity) overflow.push(it.id);
    let need = it.h;
    if (it.keepNext && items[i + 1] && !items[i + 1].newPage && !items[i + 1].own) need += items[i + 1].h;
    if (cur.used + need > capacity && cur.items.length) flush();
    cur.items.push(it.id); cur.used += it.h;
    if (it.own) flush();
  }
  flush();
  return { pages, overflow };
}
export const pageCount = (model, paper) => { const items = layoutItems(model, paper); return paginate(items, contentBox(paper).h).pages.length; };
