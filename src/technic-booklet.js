// BUILT §304 — THE BOOKLET, the pure half: a printable instruction booklet for one LEGO Technic build, as DATA.
// Pure: no three.js, no DOM, so the probe that holds it (tools/probe-technic-booklet.mjs) and the page that
// prints it (booklet.html) read one module. The page draws; this module decides WHAT is drawn, WHERE the
// camera stands, WHICH parts a step's callout shows, WHAT a step must say, and HOW the pages break.
//
// WHAT THE BOOKLET IS. A cover; the parts list (the §300/§301 bill of materials, a picture a line); the steps
// (the §302 plan, every step on exactly one page, in order); a closing page. One source, two papers: US
// Letter and A4 differ in width and height, so the same steps break onto different pages, and every number
// that sizes a page below is derived from the paper and the printer's unprintable edge, never typed per size.
//
// MODELLED, NOT BUILT. The booklet describes a model nobody has assembled. A step the swept-insertion validator
// (BUILT §302) could not clear is MARKED on its page with the reason, never shown as buildable, and the verdicts
// come from src/technic-booklet-flags.js (generated by tools/booklet-flags.mjs, signed with the plan they were
// measured on); a booklet whose verdicts belong to another plan marks EVERY part step as unchecked rather than
// show them clean.
import { walk, bounds, LDU_MM } from './ldraw.js';
import { viewBasis, packInfo, foldParts, honestyFor, NOT_IN_MODEL, CORD_ROLES } from './technic-bom.js';
import { planSig } from './technic-booklet-sig.js';

export { planSig };

// ---------------------------------------------------------------------------
// THE PAPER. CSS pixels are 1/96 in. A page's printable box is the sheet less an unprintable edge every
// consumer printer leaves (a quarter inch, the figure printers quote), doubled so the content sits a quarter
// inch inside what the printer can reach: that is the one margin. The footer line is carved out of the content
// height, not out of the margin.
export const PX_PER_IN = 96, MM_PER_IN = 25.4;
export const NONPRINTABLE_IN = 0.25;
export const MARGIN_PX = 2 * NONPRINTABLE_IN * PX_PER_IN;
export const FOOT_PX = 28;
export const PAPERS = Object.freeze({
  letter: Object.freeze({ id: 'letter', name: 'US Letter', css: '8.5in 11in', w: 8.5 * PX_PER_IN, h: 11 * PX_PER_IN }),
  a4: Object.freeze({ id: 'a4', name: 'A4', css: '210mm 297mm', w: 210 / MM_PER_IN * PX_PER_IN, h: 297 / MM_PER_IN * PX_PER_IN }),
});
export const PAPER_IDS = Object.freeze(Object.keys(PAPERS));
export const contentBox = (paper) => ({ w: paper.w - 2 * MARGIN_PX, h: paper.h - 2 * MARGIN_PX - FOOT_PX });
// regions that print Letter by default; everyone else A4 (a default, and a flip: ?paper= wins)
export const LETTER_REGIONS = Object.freeze(['US', 'CA', 'MX', 'PH', 'CL', 'CO', 'VE', 'GT', 'CR', 'PR']);
export const defaultPaper = (lang) => (LETTER_REGIONS.includes(/[-_]([A-Za-z]{2})\b/.exec(lang ?? '')?.[1]?.toUpperCase()) ? 'letter' : 'a4');

// ---------------------------------------------------------------------------
// THE CARD. A step is a card: a callout column (the step's number and the parts it adds) beside the picture,
// the title and text under both. The picture is a fixed box so a card's height does not wait on a render;
// it grows only when the callout holds more pips than the picture is tall.
//
// THE PICTURE'S HEIGHT is derived, not chosen: a chapter band and THREE two-line cards must fit the SHORTEST
// page (US Letter's content box) with SLACK_PX to spare, so every paper shows three steps to a page and a
// taller page (A4) only gains slack. What a "two-line card" is: padding both sides, a border, a title line and
// two text lines.
const CARD = { font: 11, line: 15, title: 13, titleLine: 18, callW: 168, gap: 14, pipW: 80, pipH: 92, pipGap: 4, numH: 44, cardPad: 16, cardBorder: 2, cardGap: 10, bodyGap: 8, chapterH: 46 };
export const STEPS_PER_PAGE = 3, SLACK_PX = 8;
const typicalBody = CARD.bodyGap + CARD.titleLine + 2 * CARD.line;
const shortest = Math.min(...Object.values(PAPERS).map((p) => p.h - 2 * MARGIN_PX - FOOT_PX));
export const LAYOUT = Object.freeze({ ...CARD,
  imgH: Math.floor((shortest - CARD.chapterH - SLACK_PX) / STEPS_PER_PAGE - (2 * CARD.cardPad + CARD.cardBorder + CARD.cardGap + typicalBody)) });
// the picture is drawn at twice its CSS size: 192 dpi on paper
export const RENDER_SCALE = 2;
// Text measure: the average advance of the page's sans-serif as a fraction of its size, plus the waste of
// wrapping at word ends; high on purpose (the estimate may over-count a line, never under-count one)
export const CHAR_EM = 0.56, CHAR_EM_BOLD = 0.62, WRAP_WASTE = 1.06;
export const textLines = (s, widthPx, fontPx = LAYOUT.font, em = CHAR_EM) => (s ? Math.max(1, Math.ceil(String(s).length * em * fontPx * WRAP_WASTE / widthPx)) : 0);
// a marker's box: its padding and its top margin, round the lines of its label and text
export const MARK_BOX_PX = 16;
// the picture's box: the card's inner width (less its padding and border) beside the callout column
export const innerWidth = (paper) => contentBox(paper).w - 2 * LAYOUT.cardPad - LAYOUT.cardBorder;
export const imageBox = (paper) => ({ w: Math.floor(innerWidth(paper) - LAYOUT.callW - LAYOUT.gap), h: LAYOUT.imgH });
export const cardWidth = (paper) => contentBox(paper).w;

// ---------------------------------------------------------------------------
// WHERE THE CAMERA STANDS. Every picture is the part pictures' corner view (BUILT §300: azimuth 45 degrees,
// elevation 30), so a callout and a step read alike. The frame is the step's own, derived from the geometry:
//   the NEW parts' surface, plus every part already placed that stands within CONTEXT_LDU of them (the neighbours
//   a builder must see them against: what they rest on and mesh with; the baseplate is excluded, it would frame
//   the whole table for every step), plus the arrow that shows the way in; padded by PICTURE_PAD and widened to
//   the picture's aspect; never narrower than MIN_FRAME_LDU.
export const CONTEXT_LDU = 20;           // one stud pitch
export const MIN_FRAME_LDU = 60;         // three studs across: one 8T gear does not fill the page
export const FRAME_PAD = 0.12;           // BUILT §300's PICTURE_PAD
export const ARROW_LEN_LDU = 50, ARROW_GAP_LDU = 6;
// A turn-to-mesh arc rides the gear's pitch circle plus an addendum: pitch radius is N * 1.25 LDU (the pack's
// 1 mm module, MESH 0.5 mm a tooth), the arc stands 10 LDU outside the tips.
export const PITCH_LDU_PER_TOOTH = 1.25, TURN_STANDOFF_LDU = 10, TURN_SWEEP_DEG = 270, TURN_START_DEG = 20, TURN_SEGMENTS = 36;

const sub3 = (u, v) => [u[0] - v[0], u[1] - v[1], u[2] - v[2]];
const dot3 = (u, v) => u[0] * v[0] + u[1] * v[1] + u[2] * v[2];
const cross3 = (u, v) => [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]];
const norm3 = (u) => { const n = Math.hypot(...u); return n > 1e-12 ? u.map((v) => v / n) : u; };
const at3 = (m, l) => [m[0] + m[3] * l[0] + m[4] * l[1] + m[5] * l[2], m[1] + m[6] * l[0] + m[7] * l[1] + m[8] * l[2], m[2] + m[9] * l[0] + m[10] * l[1] + m[11] * l[2]];
const DIRS = { down: [0, 1, 0], up: [0, -1, 0], '+x': [1, 0, 0], '−x': [-1, 0, 0], '+z': [0, 0, 1], '−z': [0, 0, -1] };

// a part's unique surface vertices in its own frame, once per library
const vertMemo = new WeakMap();
export function vertsOf(lib, id) {
  let m = vertMemo.get(lib); if (!m) vertMemo.set(lib, m = new Map());
  if (m.has(id)) return m.get(id);
  const seen = new Set(), out = [];
  walk(lib, `${id}.dat`, (kind, pts) => {
    if (kind !== 'tri') return;
    for (const p of pts) { const k = `${Math.round(p[0] * 100)},${Math.round(p[1] * 100)},${Math.round(p[2] * 100)}`; if (!seen.has(k)) { seen.add(k); out.push(p); } }
  });
  m.set(id, out);
  return out;
}
const boxMemo = new WeakMap();
export function worldBox(lib, p) {                                  // the part's placed axis-aligned box, LDU
  let m = boxMemo.get(lib); if (!m) boxMemo.set(lib, m = new Map());
  if (!m.has(p.part)) m.set(p.part, bounds(lib, `${p.part}.dat`));
  const b = m.get(p.part), lo = [Infinity, Infinity, Infinity], hi = [-Infinity, -Infinity, -Infinity];
  for (const x of [b.lo[0], b.hi[0]]) for (const y of [b.lo[1], b.hi[1]]) for (const z of [b.lo[2], b.hi[2]]) {
    const w = at3(p.m, [x, y, z]); for (let k = 0; k < 3; k++) { lo[k] = Math.min(lo[k], w[k]); hi[k] = Math.max(hi[k], w[k]); }
  }
  return { lo, hi };
}
const unionBox = (boxes) => { const lo = [Infinity, Infinity, Infinity], hi = [-Infinity, -Infinity, -Infinity]; for (const b of boxes) for (let k = 0; k < 3; k++) { lo[k] = Math.min(lo[k], b.lo[k]); hi[k] = Math.max(hi[k], b.hi[k]); } return { lo, hi }; };
const near = (A, B, d) => [0, 1, 2].every((k) => A.lo[k] - d < B.hi[k] && B.lo[k] - d < A.hi[k]);

// view-plane coordinates of a world point (x right, y up), and back to the picture's 0..1
export function planePoint(p, basis = viewBasis()) { return [dot3(p, basis.right), dot3(p, basis.up)]; }
export const toImage = (frame, q) => [(q[0] - (frame.cx - frame.hw)) / (2 * frame.hw), ((frame.cy + frame.hh) - q[1]) / (2 * frame.hh)];

// the arrow that shows the way in: tail behind the new parts, head just short of their near face
export function insertArrow(box, dir) {
  const C = [0, 1, 2].map((k) => (box.lo[k] + box.hi[k]) / 2);
  let h = 0;
  for (const x of [box.lo[0], box.hi[0]]) for (const y of [box.lo[1], box.hi[1]]) for (const z of [box.lo[2], box.hi[2]]) h = Math.max(h, Math.abs(dot3(sub3([x, y, z], C), dir)));
  const tail = C.map((v, k) => v - dir[k] * (h + ARROW_GAP_LDU + ARROW_LEN_LDU)), head = C.map((v, k) => v - dir[k] * (h + ARROW_GAP_LDU));
  return { tail, head };
}
// the turn-to-mesh arc about a gear's axle: points on the circle in the plane perpendicular to the gear's Z
export function turnArc(p) {
  const O = [p.m[0], p.m[1], p.m[2]], A = norm3([p.m[5], p.m[8], p.m[11]]);
  const u = norm3(Math.abs(A[1]) < 0.9 ? cross3(A, [0, 1, 0]) : cross3(A, [1, 0, 0])), v = cross3(A, u);
  const R = p.teeth * PITCH_LDU_PER_TOOTH + TURN_STANDOFF_LDU, pts = [];
  for (let k = 0; k <= TURN_SEGMENTS; k++) {
    const a = (TURN_START_DEG + TURN_SWEEP_DEG * k / TURN_SEGMENTS) * Math.PI / 180;
    pts.push(O.map((c, i) => c + R * (Math.cos(a) * u[i] + Math.sin(a) * v[i])));
  }
  return pts;
}

function projectExtent(lib, parts, idx, basis, into) {
  for (const i of idx) {
    const p = parts[i];
    for (const v of vertsOf(lib, p.part)) {
      const w = at3(p.m, v), x = dot3(w, basis.right), y = dot3(w, basis.up);
      into.x0 = Math.min(into.x0, x); into.x1 = Math.max(into.x1, x); into.y0 = Math.min(into.y0, y); into.y1 = Math.max(into.y1, y);
    }
  }
}
// A frame (view-plane centre and half extents) holding `extent`, padded and widened to the picture's aspect.
export function frameOf(ext, aspect) {
  const w = Math.max(ext.x1 - ext.x0, MIN_FRAME_LDU), h = Math.max(ext.y1 - ext.y0, MIN_FRAME_LDU / aspect);
  const hh = Math.max(h / 2, w / 2 / aspect) * (1 + FRAME_PAD);
  return { cx: (ext.x0 + ext.x1) / 2, cy: (ext.y0 + ext.y1) / 2, hw: hh * aspect, hh };
}
export const inFrame = (frame, q, eps = 1e-6) => Math.abs(q[0] - frame.cx) <= frame.hw + eps && Math.abs(q[1] - frame.cy) <= frame.hh + eps;

// The whole build in one frame (the cover, the closing page, the last step's picture).
export function wholeFrame(plan, lib, aspect, basis = viewBasis()) {
  const ext = { x0: Infinity, x1: -Infinity, y0: Infinity, y1: -Infinity };
  projectExtent(lib, plan.parts, plan.parts.map((_, i) => i), basis, ext);
  return frameOf(ext, aspect);
}

// ---------------------------------------------------------------------------
// THE VIEWS. For each step: which placements stand as ghosts (already built, drawn pale), which are fresh (this
// step's, drawn in their colours with the x-ray of anything a ghost hides), the frame, the arrows. A
// sub-assembly's steps are drawn on their own (they are built OFF the model); its `place` step shows the finished
// unit lowered into the main build. `kind: 'note'` steps add nothing and have no picture.
export function viewSpecs(plan, lib, { aspect, flagSteps = null, basis = viewBasis() } = {}) {
  const specs = new Map(), main = [], subs = new Map();
  const all = plan.parts.map((_, i) => i);
  for (const st of plan.steps) {
    let spec = null;
    if (st.kind === 'final') {
      spec = { n: st.n, scope: 'main', ghost: [], fresh: all, arrows: [], frame: wholeFrame(plan, lib, aspect, basis), framed: all };
    } else if (st.kind === 'note') {
      spec = null;
    } else if (st.sub) {
      const before = subs.get(st.sub) ?? [];
      spec = { n: st.n, scope: 'sub', sub: st.sub, ghost: [...before], fresh: [...st.parts], arrows: [] };
      subs.set(st.sub, [...before, ...st.parts]);
    } else {
      const fresh = st.parts.length ? st.parts : (st.unit ?? []);
      spec = { n: st.n, scope: 'main', ghost: [...main], fresh: [...fresh], arrows: [] };
      for (const i of fresh) main.push(i);
    }
    if (spec && st.kind !== 'final') {
      // arrows
      const fb = unionBox(spec.fresh.map((i) => worldBox(lib, plan.parts[i])));
      if (st.kind !== 'final' && st.kind !== 'baseplate' && !st.flexible) {
        const named = flagSteps?.[st.n]?.d, dir = named && DIRS[named] ? DIRS[named] : (st.cand?.[st.parts[0]]?.[0] ?? st.cand?.unit?.[0] ?? DIRS.down);
        spec.arrows.push({ type: 'insert', dir, ...insertArrow(fb, dir), dirName: named ?? null });
      }
      for (const m of st.meshes ?? []) if (spec.fresh.includes(m.part)) spec.arrows.push({ type: 'turn', part: m.part, partner: m.partner, phi: m.phi, pts: turnArc(plan.parts[m.part]) });
      // frame
      const ext = { x0: Infinity, x1: -Infinity, y0: Infinity, y1: -Infinity };
      const shown = new Set(spec.fresh);
      const grow = { lo: fb.lo.map((v) => v), hi: fb.hi.map((v) => v) };
      if (spec.scope === 'main' && st.kind !== 'final') {
        for (const g of spec.ghost) if (plan.parts[g].role !== 'baseplate' && near(grow, worldBox(lib, plan.parts[g]), CONTEXT_LDU)) shown.add(g);
      } else if (spec.scope === 'sub') for (const g of spec.ghost) shown.add(g);
      projectExtent(lib, plan.parts, [...shown], basis, ext);
      for (const a of spec.arrows) for (const q of a.type === 'insert' ? [a.tail, a.head] : a.pts) { const [x, y] = planePoint(q, basis); ext.x0 = Math.min(ext.x0, x); ext.x1 = Math.max(ext.x1, x); ext.y0 = Math.min(ext.y0, y); ext.y1 = Math.max(ext.y1, y); }
      spec.frame = frameOf(ext, aspect);
      spec.framed = [...shown];
      for (const a of spec.arrows) a.img = (a.type === 'insert' ? [a.tail, a.head] : a.pts).map((q) => toImage(spec.frame, planePoint(q, basis)));
    }
    specs.set(st.n, spec);
  }
  return specs;
}

// ---------------------------------------------------------------------------
// THE CALLOUT: the parts a step adds, folded like the BOM (a cord's pieces are the one string), each line
// matched to the BOM line it is a share of.
export function calloutOf(plan, st, bom) {
  const idx = st.parts.length ? st.parts : [];
  if (!idx.length) return [];
  const parts = idx.map((i) => plan.parts[i]);
  const isString = parts.some((p) => CORD_ROLES.includes(p.role));
  const f = foldParts(parts, { string: isString ? plan.build.cord?.string ?? null : null });
  const byKey = new Map(bom.lines.map((l) => [`${l.part}|${l.colour}`, l]));
  return f.lines.map((l) => {
    const b = byKey.get(`${l.part}|${l.colour}`);
    if (!b) throw new Error(`booklet: step ${st.n} adds ${l.part} in colour ${l.colour}, which the parts list does not hold`);
    return { part: l.part, colour: l.colour, qty: l.qty, title: b.title, hex: b.hex, colourName: b.colourName, status: b.status, only2026: b.only2026, line: b };
  });
}

// ---------------------------------------------------------------------------
// THE MARKS: what a step must say besides what it adds.
export const FLAG_TODO = 264;
// `name` says a part's id in words (the page hands the pack's title); the default is the id alone
export function flagText(it, name = (id) => id) {
  const by = it.by ? `part ${name(it.by)}` : 'a neighbouring part';
  const dep = it.depth != null ? ` It reaches ${it.depth} LDU into ${by} where ${it.allow} LDU is allowed.` : '';
  return `NOT CLEARED. The swept-insertion check found no path that puts ${it.part === 'unit' ? 'this sub-assembly' : `part ${name(it.part)}`} in without touching ${by}.${dep} As modelled, this step may need a part or its neighbour changed before it can be built (TODO ${FLAG_TODO}).`;
}
export function overlapText(it, name = (id) => id) {
  return `TWO SOLIDS IN EACH OTHER. As modelled, part ${name(it.part)} stands ${it.depth} LDU inside part ${name(it.with)} once this step is done, deeper than any part is moulded to be pressed (a fact about the model, TODO ${FLAG_TODO}): this step cannot be completed as drawn.`;
}
export const turnText = (it) => `Found only with the meshed gears turned: the check lowered part ${it.part} with its neighbours turned ${it.deg} degrees.`;
export const twoLegText = (it) => `Found only in two moves: lower ${it.part === 'unit' ? 'the sub-assembly' : `part ${it.part}`}, then slide it ${it.ldu} LDU (${(it.ldu * LDU_MM).toFixed(1)} mm) along ${it.along}.`;
export const UNCHECKED_TEXT = 'NOT CHECKED. The insertion verdicts belong to another plan than this one (the derivation has moved since they were written), so this step has no verdict.';

// the verdict table's row for this plan, or why there is none
export function flagsFor(table, plan, gen, cell, mode, SHARED = ['fusee', 'alarm', 'escapement']) {
  const key = `${SHARED.includes(cell) ? 'shared' : gen}|${cell}|${mode ?? '-'}`, row = table?.[key];
  if (!row) return { status: 'missing', key, steps: {} };
  if (row.sig !== planSig(plan)) return { status: 'stale', key, steps: {} };
  return { status: 'ok', key, steps: row.steps };
}

