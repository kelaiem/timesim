// §338 landing 2 — DETERMINISTIC MATHS: the elementary functions the build
// computes with, made a property of THIS REPOSITORY instead of the engine.
//
// WHY. ECMA-262 leaves Math.sin, Math.pow, Math.hypot and the other
// transcendentals "implementation-approximated". Measured (§338): V8 12.4 and
// V8 15.3 disagree by 1 ulp on 2–11% of inputs for every one of them except
// sqrt, JavaScriptCore differs again, and those last bits were enough to move
// coordinates by ~1e-17 and flip the vertex count of 1–3 meshes per spec. So
// the same source built different metal on different engines and on different
// releases of ONE engine, which no gate measured.
//
// WHAT. installDetMath() replaces each implementation-approximated Math
// function with a pure-JavaScript port of FreeBSD msun / Sun fdlibm (vendored,
// GENERATED by tools/det-math-vendor.mjs: vendor/det-math.module.js). Those
// ports use only + − × ÷, sqrt and bit reads, which IEEE 754 makes identical on
// every conforming engine and CPU, so the results are too: bit-identical on V8
// 12.4, V8 15.3 and JavaScriptCore over 40,000 inputs per function, and within
// 2 ulp of V8's own. The exact functions (abs, floor, ceil, round, trunc, sign,
// min, max, sqrt, fround, imul, clz32) are left as the engine's: ECMA-262 or
// IEEE 754 already defines their every bit.
//
// ONE INSTALL POINT PER HOST, BEFORE ANYTHING COMPUTES. The page installs in
// src/det-math-boot.js, the entry module's FIRST import (a module's
// dependencies evaluate in import order, so every module after it, three.js
// included, calls the installed functions); the native host installs in
// tools/native/host.mjs before it imports main.js. A host that skips it boots
// with a warning (main.js reads __detMath), never silently.
//
// THE `**` OPERATOR cannot be reached by replacing Math.pow: it is the engine's
// own exponentiation. So the build does not use it: tools/check-det-math.mjs
// holds index.html's module graph free of `**` (two vendored sites are listed
// there with the reason each is exact).
//
// What this does NOT cover: pages that do not import det-math-boot.js
// (technic.html, booklet.html, gong-bench.html, service-life.html, test-geometry.html, explain and
// primer), Web Workers, and tools that import src/ builders under
// tools/three-node-loader.mjs. None of them feeds the battery.
import * as S from '../vendor/det-math.module.js';

// ECMA-262 Number::exponentiate, steps 1–11, applied here because stdlib's pow
// follows C at the special values and is wrong at some (measured: pow(NaN, 0),
// pow(±1, ±Infinity), the ±0 and −Infinity bases, and its odd-integer test,
// which reads y − 1 and so calls 1e300 odd). stdlib is asked only for a finite
// positive base and a finite non-zero exponent.
const isOddInteger = (y) => y % 2 === 1 || y % 2 === -1;   // exact for every double; |y| ≥ 2^53 is even
function pow(base, exponent) {
  const b = +base, y = +exponent;
  if (y !== y) return NaN;
  if (y === 0) return 1;
  if (b !== b) return NaN;
  if (b === Infinity) return y > 0 ? Infinity : 0;
  if (b === -Infinity) return y > 0 ? (isOddInteger(y) ? -Infinity : Infinity) : (isOddInteger(y) ? -0 : 0);
  if (b === 0) {
    if (Object.is(b, 0)) return y > 0 ? 0 : Infinity;
    return y > 0 ? (isOddInteger(y) ? -0 : 0) : (isOddInteger(y) ? -Infinity : Infinity);
  }
  if (y === Infinity) { const a = b < 0 ? -b : b; return a > 1 ? Infinity : a === 1 ? NaN : 0; }
  if (y === -Infinity) { const a = b < 0 ? -b : b; return a > 1 ? 0 : a === 1 ? NaN : Infinity; }
  if (b < 0) {
    if (Math.trunc(y) !== y) return NaN;
    const r = S.pow(-b, y);
    return isOddInteger(y) ? -r : r;
  }
  return S.pow(b, y);
}

// Math.hypot, ECMA-262 21.3.2.18: every argument coerced first; any ±Infinity
// gives +Infinity (even beside a NaN), else any NaN gives NaN, all zeros give
// +0; otherwise approximated, here as m·√Σ(xᵢ/m)² with m the largest |xᵢ|,
// summed in argument order. Every operation in it is correctly rounded, so the
// result is the same on every engine; scaling by m keeps it from overflowing
// or underflowing where the true value does not.
function hypot(x, y) {
  const n = arguments.length;
  if (n === 2) {
    let a = +x, c = +y;
    if (a < 0) a = -a;
    if (c < 0) c = -c;
    if (a === Infinity || c === Infinity) return Infinity;
    if (a !== a || c !== c) return NaN;
    const m = a > c ? a : c;
    if (m === 0) return 0;
    const r = (a > c ? c : a) / m;
    return m * Math.sqrt(1 + r * r);
  }
  const v = new Array(n);
  let m = 0, inf = false, nan = false;
  for (let i = 0; i < n; i++) {
    let a = +arguments[i];
    if (a < 0) a = -a;
    v[i] = a;
    if (a === Infinity) inf = true; else if (a !== a) nan = true; else if (a > m) m = a;
  }
  if (inf) return Infinity;
  if (nan) return NaN;
  if (m === 0) return 0;
  let s = 0;
  for (let i = 0; i < n; i++) { const r = v[i] / m; s += r * r; }
  return m * Math.sqrt(s);
}

// The installed set: every Math function ECMA-262 leaves implementation-
// approximated. Each coerces its argument the way the builtin does (unary +,
// which throws on a BigInt exactly as the builtin's ToNumber does).
export const DET_MATH = Object.freeze({
  sin: (x) => S.sin(+x), cos: (x) => S.cos(+x), tan: (x) => S.tan(+x),
  asin: (x) => S.asin(+x), acos: (x) => S.acos(+x), atan: (x) => S.atan(+x),
  atan2: (y, x) => S.atan2(+y, +x),
  exp: (x) => S.exp(+x), expm1: (x) => S.expm1(+x),
  log: (x) => S.log(+x), log1p: (x) => S.log1p(+x), log2: (x) => S.log2(+x), log10: (x) => S.log10(+x),
  cbrt: (x) => S.cbrt(+x),
  sinh: (x) => S.sinh(+x), cosh: (x) => S.cosh(+x), tanh: (x) => S.tanh(+x),
  asinh: (x) => S.asinh(+x), acosh: (x) => S.acosh(+x), atanh: (x) => S.atanh(+x),
  pow, hypot,
});

// Replace them on `M` (the realm's Math), keeping the builtins' property shape
// (writable, configurable, not enumerable). Idempotent.
export function installDetMath(M = Math) {
  for (const [name, fn] of Object.entries(DET_MATH)) {
    if (M[name] !== fn) Object.defineProperty(M, name, { value: fn, writable: true, configurable: true, enumerable: false });
  }
  return Object.keys(DET_MATH).every((k) => M[k] === DET_MATH[k]);
}

// KNOWN ANSWERS: each installed function over a fixed input set (an integer
// LCG mapped into each function's domain, plus the special values), its
// results hashed as raw bits with every NaN made one pattern (engines differ in
// NaN bits; a NaN is a NaN). The hashes are RECORDED in src/det-math-kat.js by
// tools/det-math-kat.mjs, so they are what this library computes, written down;
// a host whose arithmetic does not reproduce them is a host this build cannot
// trust, and it says so at boot. `n` inputs per function; the boot uses a few
// hundred (a few ms), the tool and the probes many more.
export function knownAnswers(n = 256, M = DET_MATH) {
  const SPECIAL = [0, -0, 1, -1, 0.5, -0.5, 2, -2, 3, Infinity, -Infinity, NaN, 5e-324, -5e-324,
    2.2250738585072014e-308, 1.7976931348623157e308, Math.PI, -Math.PI, 1e-300, 1e300, 0.1, 710, -745];
  const f64 = new Float64Array(1), u32 = new Uint32Array(f64.buffer);
  let seed = 0x2545f491;
  const rnd = () => { seed = (Math.imul(seed, 1103515245) + 12345) >>> 0; return seed / 4294967296; };
  const xs = [...SPECIAL];
  for (let i = 0; i < n; i++) {
    const u = rnd(), k = i % 4;
    xs.push(k === 0 ? (u - 0.5) * 25 : k === 1 ? (u - 0.5) * 2.5 : k === 2 ? (u - 0.5) * 2e-3 : (u - 0.5) * 2e6);
  }
  const ys = xs.map((x, i) => xs[(i * 7 + 3) % xs.length]);
  const mix = (h, v) => {
    if (v !== v) { u32[0] = 0; u32[1] = 0x7ff80000; } else f64[0] = v;
    h = Math.imul(h ^ u32[0], 16777619);
    return Math.imul(h ^ u32[1], 16777619);
  };
  const out = {};
  for (const name of Object.keys(DET_MATH)) {
    const f = M[name];
    let h = 0x811c9dc5;
    for (let i = 0; i < xs.length; i++) {
      h = mix(h, name === 'atan2' || name === 'pow' || name === 'hypot' ? f(xs[i], ys[i])
        : f(name === 'exp' || name === 'expm1' || name === 'sinh' || name === 'cosh' ? xs[i] / 500 : xs[i]));
    }
    if (name === 'hypot') { h = mix(h, f()); h = mix(h, f(3)); h = mix(h, f(1, 2, 3, 4)); h = mix(h, f(NaN, Infinity)); h = mix(h, f(-0, 0)); }
    out[name] = h >>> 0;
  }
  return out;
}
