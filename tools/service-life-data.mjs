#!/usr/bin/env node
// WRITES src/service-life-data.json: what service-life.html draws — the escape
// wheel's club tooth and the century of wear TODO 299 prices on it. The page
// cannot boot the movement (it is display only and sim-code-free, like the gong
// bench: the battery never sees it), so the record is GENERATED here from a
// booted build and committed, never typed, and --check re-derives it.
//
//   node --import ./tools/native/loader.mjs tools/service-life-data.mjs --write
//   node --import ./tools/native/loader.mjs tools/service-life-data.mjs --check
//
// One native boot (§338: the native host builds the browser's movement digest
// for digest, so this needs no browser), about twenty seconds.
//
// WHAT IT COPIES, and nothing else: the energy column's `escapeTooth` record —
// the wear row (TODO 299: Archard over the century, three K corners, the
// budget the lock can spend), the finish (TODO 299 landing 2: the tip's radius
// and the reach it spends) and the wedge (TODO 296: the club's flanks off the
// AUTHORED outline) — plus that outline itself, `escapeWheel.userData.profile`,
// the polygon the wedge was read off. It does NO arithmetic of its own: every
// number the page shows is either copied from the build's record or one of the
// record's own identities applied on the page (the depth goes as √t because the
// volume goes as t and the depth as √volume), so --check is exactly "the build's
// record has not moved". A record that moves owes a re-run, the way a seat table
// does the gong bench's (TODO 279 is why this one is gated from its first day:
// native-host.yml runs --check on both architectures). Since §346 it also copies
// the oil-ageing record (`going.energy.oilAgeing`): a POSED law's samples, which
// the page draws as the balance's swing falling across each interval.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/service-life-data.json');
const ARGS = process.argv.slice(2), WRITE = ARGS.includes('--write'), CHECK = ARGS.includes('--check');
if (WRITE === CHECK) { console.error('usage: node --import ./tools/native/loader.mjs tools/service-life-data.mjs --write | --check'); process.exit(2); }

const { bootNative } = await import('./native/host.mjs');
const L = await import('../src/layout.js');
const r = await bootNative({ query: '' });
if (r.warns.length) { console.error(`FAIL: the build booted with ${r.warns.length} warning(s) — a record off a loud boot is not the build's: ${r.warns[0]}`); process.exit(1); }
const et = r.clock.equalisation?.going?.energy?.escapeTooth;
if (!et?.wear || !et?.geom || !et?.landing?.finish) { console.error('FAIL: the build carries no escapeTooth wear record (TODO 299)'); process.exit(1); }
if (!r.clock.equalisation.going.energy.oilAgeing) { console.error('FAIL: the build carries no oil-ageing record (§346)'); process.exit(1); }
const g = et.geom, w = et.wear, fin = et.landing.finish;

// the wheel the wedge was read off: the one object carrying a club profile at the record's radius
let wheel = null, n = 0;
r.clock.scene.traverse((o) => { if (o.userData?.profile?.poly && Math.abs(o.userData.r - g.radius_u) < 1e-12) { wheel = o; n++; } });
if (n !== 1) { console.error(`FAIL: ${n} objects carry a club profile at r ${g.radius_u} (want exactly the escape wheel)`); process.exit(1); }
const poly = wheel.userData.profile.poly;
// the tip the record names must be a vertex of this outline, or the wheel is not the one it was read off
const ti = poly.findIndex((p) => Math.hypot(p[0] - g.tip.xy[0], p[1] - g.tip.xy[1]) < 1e-12);
if (ti < 0) { console.error('FAIL: the record\'s tip is not a vertex of the escape wheel\'s outline'); process.exit(1); }

const q = (x, d = 9) => (Number.isFinite(x) ? Number(x.toPrecision(d)) : x);
const corner = (c) => ({ K: c.K, volume_m3: q(c.volume_m3), recession_m: q(c.recession_m), overBudget: q(c.overBudget) });
const data = {
  about: 'GENERATED by tools/service-life-data.mjs from a booted build — never edit; --check re-derives it',
  unitMm: L.UNIT_MM,
  steelRho_kgm3: L.STOCK.steel.rho,
  wheel: {
    teeth: poly.filter((p) => Math.abs(Math.hypot(p[0], p[1]) - g.tip.r) < 1e-9).length,   // the tips ON the tooth circle, counted, never typed
    radius_u: g.radius_u,
    thickness_u: g.band.t_u,
    // 12 digits, not 9: the page re-derives the finish's cut-back (a 0.0035 u difference of two ~4.5 u radii) off
    // these vertices, and the smoke holds it to the build's at 1e-6 — at 8 digits the rounding alone read 1e-5
    poly: poly.map(([x, y]) => [q(x, 12), q(y, 12)]),
    tipIndex: ti,
    tip: { xy: g.tip.xy.map((v) => q(v)), r: q(g.tip.r), azDeg: q(g.tip.azDeg) },
    wedge: { fullDeg: q(g.wedge.fullDeg), lockFlankDeg: q(g.wedge.lockFlankDeg), impulseFlankDeg: q(g.wedge.impulseFlankDeg),
      bisectorDeg: q(g.wedge.bisectorRad * 180 / Math.PI), widthPerDepth: q(g.wedge.widthPerDepth) },
  },
  finish: { rho_m: q(fin.rho_m), cutBack_u: q(fin.cutBack_u) },
  wear: {
    years: w.years, serviceYears: w.serviceYears, services: w.services,
    engagementsPerTooth: w.engagementsPerTooth, slipPerEngagement_m: q(w.slipPerEngagement_m), slip_m: q(w.slip_m),
    load_N: q(w.load_N), hardness_Pa: w.hardness_Pa, hardnessHV: w.hardnessBand.lowHV,
    kBand: { favourable: w.kBand.favourable, nominal: w.kBand.nominal, adverse: w.kBand.adverse, why: w.kBand.why },
    fromApex_u: q(w.fromApex_u), cutBack_u: q(w.cutBack_u), budget_u: q(w.budget_u),
    lockRunFull_u: q(w.lockRunFull_u), lockOnly_u: q(w.lockOnly_u),
    corners: { favourable: corner(w.corners.favourable), nominal: corner(w.corners.nominal), adverse: corner(w.corners.adverse) },
    needHardnessHV: Object.fromEntries(Object.entries(w.needHardness_Pa).map(([c, v]) => [c, q(v / L.HV_TO_PA, 6)])),
    holdsAt: w.holdsAt,
    beats: w.counts.beats, escapeTurns: w.counts.turns.escape,
  },
  // §346 — the oil's ageing across each interval (a POSED law, layout.js OIL_AGEING): the
  // rows that age, their two corners and the swing the column sustains at each sample,
  // which the page joins by straight lines (the record derived the spacing for that).
  oilAgeing: (() => {
    const O = r.clock.equalisation.going.energy.oilAgeing;
    return {
      posed: O.posed, shape: O.shape, why: O.why, fresh: O.fresh, aged: O.aged, rows: O.rows, held: O.held,
      coefficients: O.coefficients, intervalYears: O.intervalYears, readDeg: O.readDeg, intervals: O.intervals,
      interpErrDeg: q(O.interpErrDeg),
      samples: O.samples.map((s) => ({ f: s.f, years: q(s.years), etaTotal: q(s.etaTotal),
        vertical: q(s.sustainedDeg.vertical), flat: q(s.sustainedDeg.flat) })),
      dropDeg: { vertical: q(O.dropDeg.vertical), flat: q(O.dropDeg.flat) },
      targetDeg: O.targetDeg, claimDeg: O.claimDeg, knockDeg: q(r.clock.equalisation.going.energy.knock.deg),
    };
  })(),
};
const text = JSON.stringify(data, null, 1) + '\n';
if (CHECK) {
  let cur = '';
  try { cur = readFileSync(OUT, 'utf8'); } catch { /* absent reads as stale */ }
  if (cur !== text) { console.error('FAIL: src/service-life-data.json is not what the build derives — run `node --import ./tools/native/loader.mjs tools/service-life-data.mjs --write`'); process.exit(1); }
  console.log('PASS: src/service-life-data.json re-derives from the build');
} else {
  writeFileSync(OUT, text);
  console.log(`wrote src/service-life-data.json (${(text.length / 1024).toFixed(1)} KB): ${poly.length}-vertex outline, nominal ${(w.corners.nominal.recession_m * 1e6).toFixed(2)} µm of ${(w.budget_u * L.UNIT_MM * 1000).toFixed(2)} µm`);
}
process.exit(0);
