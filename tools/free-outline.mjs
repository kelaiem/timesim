// §325 — WRITE OR CHECK src/free-outlines.js, the FREE outline each movement is cut to. ACCEPTANCE (--check exits
// non-zero on drift).
//
// The free outline is the metal's own plan (layout.js fitFreeCase: the counted metal's plan hulls, the lug ends,
// grown by the rim margin, closed by FREE_RC), so it cannot be computed before the movement is built — and the
// plates are cut to it before the parts that set it. The table carries it from one boot to the next, as
// ?formrect= carries a box. This tool closes the loop:
//
//   1. boot ?case=free with the table as it stands (the server hands the page the table this run is building, never
//      the file — the gong-seats.mjs precedent), and read the counted metal's plan hulls off __clock.formFootprint;
//   2. search the STRAP AXIS c in Node over those hulls (layout.js fitFreeCase, the build's own law): a scan every
//      SCAN_U over the metal's middle, then golden section in the best bracket to TOL_U — the least plan area;
//   3. write that row and boot again: the counted metal may follow the outline (a pillar seated on the plate, a
//      stud planted in it), so the fit is a FIXED POINT, repeated until the axis and the area stop moving and the
//      outline holds the metal (the build's own exact margin, formFootprint.margin ≥ the rim margin) with no §325
//      warning.
//
//   node tools/free-outline.mjs --write [--spec 'k=v&…']   solve the default movement's row (or the spec's) and write it
//   node tools/free-outline.mjs --check [--spec …]         re-derive and compare with the committed file
//   --fresh                                                 start from the stand-in box, not the committed row
import { readFileSync, writeFileSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import { createServer } from 'node:http';
import { fileURLToPath } from 'node:url';
import { dirname, join, normalize, extname } from 'node:path';
import { fitFreeCase, polyArea, loopSimple, UNIT_MM, PLATE_RIM_MARGIN } from '../src/layout.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/free-outlines.js');
const ARGS = process.argv.slice(2), WRITE = ARGS.includes('--write'), CHECK = ARGS.includes('--check');
const SPECQ = ARGS.includes('--spec') ? ARGS[ARGS.indexOf('--spec') + 1] : null;
if (WRITE === CHECK) { console.error('usage: node tools/free-outline.mjs --write | --check [--spec k=v&…]'); process.exit(2); }
const SCAN_U = 2.5, TOL_U = 0.05, ROUNDS = 5;
const r4 = (q) => Math.round(q * 1e4) / 1e4, mm2 = UNIT_MM * UNIT_MM;

const { FREE_OUTLINES: COMMITTED } = await import(`${join(ROOT, 'src/free-outlines.js')}?t=${Date.now()}`);
const fileText = (rows) => `// GENERATED by tools/free-outline.mjs — never edit by hand; re-run the tool (--check re-derives it).
//
// BUILT §325: per movement (the configuration key of the spec with ?case=free and no seat), the FREE outline the
// case is cut to — the strap axis c, the closing radius rc it was closed at, the lug flats' need, the plan area, the
// exact margin the metal stands inside it, and the outline itself (a closed CCW polyline, movement units). The build
// cuts its plates, dial and case to it and re-fits the measured metal at boot; a fit that no longer matches warns.
export const FREE_OUTLINES = Object.freeze(${JSON.stringify(rows, null, 1).replace(/\[\n\s+(-?[\d.]+),\n\s+(-?[\d.]+)\n\s+\]/g, '[$1, $2]')});
`;

const { chromium } = await import(join(ROOT, 'tools/node_modules/playwright/index.mjs'));
const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.json': 'application/json', '.webmanifest': 'application/json', '.png': 'image/png', '.svg': 'image/svg+xml', '.css': 'text/css' };
// --fresh starts from no row for the movement (the stand-in box), so a changed CONSTRUCTION re-derives from scratch
// rather than settling on the committed outline because the axis and the area agree with it
const FRESH = ARGS.includes('--fresh');
let rows = { ...COMMITTED };
const srv = createServer(async (req, res) => {
  try {
    const p = normalize(decodeURIComponent(new URL(req.url, 'http://x').pathname)).replace(/^(\.\.[/\\])+/, '');
    if (p === '/src/free-outlines.js') { res.writeHead(200, { 'content-type': 'text/javascript', 'cache-control': 'no-store' }).end(fileText(rows)); return; }
    const body = await readFile(join(ROOT, p === '/' ? 'index.html' : p));
    res.writeHead(200, { 'content-type': MIME[extname(p)] ?? 'application/octet-stream', 'cache-control': 'no-store' }).end(body);
  } catch { res.writeHead(404).end('nf'); }
});
await new Promise((r) => srv.listen(0, '127.0.0.1', r));
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist',
  '--disable-background-timer-throttling', '--disable-backgrounding-occluded-windows', '--disable-renderer-backgrounding'] });
const NOISE = /GPU stall|GL Driver Message|swiftshader|ReadPixels|Automatic fallback to software WebGL|no saved state|Failed to load resource/i;
const boot = async () => {
  const ctx = await browser.newContext({ viewport: { width: 800, height: 600 } }), page = await ctx.newPage(), warnings = [];
  page.on('console', (m) => { if ((m.type() === 'warning' || m.type() === 'error') && !NOISE.test(m.text())) warnings.push(m.text()); });
  page.on('pageerror', (e) => warnings.push('PAGEERROR ' + e.message));
  await page.goto(`http://127.0.0.1:${srv.address().port}/index.html?hud=0&sync=0&${SPECQ ? `${SPECQ}&` : ''}case=free`);
  await page.waitForFunction(() => !!window.__clock || !!window.__bootError, null, { timeout: 600000, polling: 1000 });
  const out = await page.evaluate(() => {
    if (window.__bootError) return { bootError: String(window.__bootError.message || window.__bootError) };
    const f = window.__clock.formFootprint;
    return { margin: f.margin, areaMm2: f.areaMm2, free: JSON.parse(JSON.stringify(f.free)) };
  });
  await ctx.close();
  return { ...out, warnings };
};

// THE STRAP AXIS: the least area over c, the scan then golden section (the build's own fit at each c)
const solveAxis = (F) => {
  let lo = Infinity, hi = -Infinity;
  for (const P of F.polys) for (const [x] of P) { lo = Math.min(lo, x); hi = Math.max(hi, x); }
  const mid = (lo + hi) / 2, half = Math.max(SCAN_U, (hi - lo) / 2 - F.need);
  const fit = (c) => { try { return fitFreeCase(F.polys, { margin: F.margin, rc: F.rc, need: F.need, c, pins: F.pins.map(([x, y, n]) => [x, y, n]) }); } catch (e) { return { area: Infinity, error: e.message }; } };
  const scan = [];
  for (let c = mid - half; c <= mid + half + 1e-9; c += SCAN_U) scan.push({ c, r: fit(c) });
  let k = 0; for (let i = 1; i < scan.length; i++) if (scan[i].r.area < scan[k].r.area) k = i;
  if (!Number.isFinite(scan[k].r.area)) throw new Error(`no strap axis admits a fit: ${scan[0].r.error}`);
  const g = (Math.sqrt(5) - 1) / 2;
  let a = scan[Math.max(0, k - 1)].c, b = scan[Math.min(scan.length - 1, k + 1)].c;
  let x1 = b - g * (b - a), x2 = a + g * (b - a), f1 = fit(x1), f2 = fit(x2);
  while (b - a > TOL_U) {
    if (f1.area <= f2.area) { b = x2; x2 = x1; f2 = f1; x1 = b - g * (b - a); f1 = fit(x1); }
    else { a = x1; x1 = x2; f1 = f2; x2 = a + g * (b - a); f2 = fit(x2); }
  }
  let best = f1.area <= f2.area ? { c: x1, r: f1 } : { c: x2, r: f2 };
  if (scan[k].r.area < best.r.area) best = scan[k];
  return { ...best, scan: scan.map(({ c, r }) => [c, r.area * mm2]) };
};

let key = null, row = null, last = null;
for (let round = 1; round <= ROUNDS; round++) {
  if (round === 1 && FRESH) rows = Object.fromEntries(Object.entries(rows).filter(([k]) => !k.includes('"caseShape":"free"') || (SPECQ && !k)));
  const b = await boot();
  if (b.bootError) throw new Error(`boot failed: ${b.bootError}`);
  key = b.free.key;
  const s = solveAxis(b.free);
  const r = s.r;
  const flat = { top: r.flat.top.map(r4), bot: r.flat.bot.map(r4), yTop: r4(r.flat.yTop), yBot: r4(r.flat.yBot), halfTop: r4(r.flat.halfTop), halfBot: r4(r.flat.halfBot) };
  row = { c: r4(s.c), rc: b.free.rc, need: b.free.need, margin: b.free.margin, area: r4(polyArea(r.pts)), worst: r4(r.worst.d), flat, keep: b.free.keep, pts: r.pts.map(([x, y]) => [r4(x), r4(y)]) };
  console.log(`round ${round}: c ${row.c} (scan ${s.scan.map(([c, A]) => `${c.toFixed(1)}:${A.toFixed(1)}`).join(' ')}) → ${(row.area * mm2).toFixed(2)} mm², margin ${row.worst}, flats ±${flat.halfTop}/${flat.halfBot} (need ${row.need.toFixed(3)}), ${row.pts.length} points, simple ${loopSimple(row.pts)}`
    + `; the cut it booted on held the metal at ${typeof b.margin === 'number' ? b.margin.toFixed(4) : b.margin}`);
  const prev = rows[key];
  rows = { ...rows, [key]: row };
  const settled = prev && Math.abs(prev.c - row.c) <= TOL_U && Math.abs(prev.area - row.area) <= 1e-3 * row.area
    && b.margin >= PLATE_RIM_MARGIN - 1e-3 && !b.warnings.some((w) => /§325/.test(w));
  if (settled) { rows = { ...rows, [key]: prev }; last = b; break; }   // the row the settled boot stood on
  last = null;
}
if (!last) {
  const b = await boot();
  last = b;
  if (!(b.margin >= PLATE_RIM_MARGIN - 1e-3) || b.warnings.some((w) => /§325/.test(w)))
    throw new Error(`the free outline did not settle in ${ROUNDS} rounds: the last boot held the metal at ${b.margin} with ${b.warnings.filter((w) => /§325/.test(w)).join(' | ')}`);
}
console.log(`settled: ${key}\n  ${(rows[key].area * mm2).toFixed(2)} mm² (the build reads ${last.areaMm2.toFixed(2)} mm²), the metal held at ${last.margin.toFixed(4)} u; other boot warnings: ${last.warnings.length}`);
for (const w of last.warnings) console.log(`    ${w.slice(0, 240)}`);
await browser.close(); srv.close();

const text = fileText(Object.fromEntries(Object.entries(rows).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))));
if (WRITE) { writeFileSync(OUT, text); console.log('wrote src/free-outlines.js'); }
else {
  const have = readFileSync(OUT, 'utf8');
  if (have !== text) { console.error('src/free-outlines.js is STALE against the movement — run node tools/free-outline.mjs --write'); process.exit(1); }
  console.log('free-outlines OK');
}
