#!/usr/bin/env node
// TODO.md and docs/BUILT.md, ONE FILE PER ITEM — the reader every tool shares,
// the split that made the layout, and the generated indexes.
//
// The two documents had grown to 2.2 and 2.5 MB, past what the GitHub app will
// open, and every branch appended to the end of the same file. So each item
// now lives in its own file, verbatim, heading included:
//
//   docs/todo/NNNN.md    one `## N. Title` item (with any unnumbered `##`
//                        sub-heading that followed it in TODO.md)
//   docs/built/NNNN.md   every section numbered §N, in the order BUILT.md had
//                        them (a § legitimately repeats: `§36 part one`, `§278,
//                        landing 4`), so one number is one file
//
// and TODO.md / docs/BUILT.md are INDEXES: a hand-written head, then a table
// GENERATED between the two markers below. Item numbers are still permanent IDs
// cited as `TODO 117` / `BUILT §278`, never by file or line, so no citation
// moved.
//
// Readers parse headings exactly as they did, over `itemText(ns, src)`: the
// item files concatenated in number order, or the old single file on a ref that
// predates the split (claim-item and check-item-numbers read OTHER refs, and an
// open branch cut before the split still carries the 2 MB file). A ref that has
// the directory never falls back, so a deleted item cannot reappear from a
// stale copy.
//
//   node tools/item-docs.mjs --check    index matches the files (CI, item-numbers.yml)
//   node tools/item-docs.mjs --write    regenerate both indexes from the files
//   node tools/item-docs.mjs --split    the one-time split (refuses once done)
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = process.env.ROOT || join(dirname(fileURLToPath(import.meta.url)), '..');

export const ITEM_DOCS = {
  TODO: { index: 'TODO.md', dir: 'docs/todo', heading: /^## (\d+)\.[ \t]*(.*)$/ },
  // The split's rule for BUILT is wider than the claim tools' heading regex:
  // `## §239, landing two` is a §239 section (the comma kept it out of the old
  // regex, which only ever needed to see SOME heading per number).
  BUILT: { index: 'docs/BUILT.md', dir: 'docs/built', heading: /^## (?:§)?(\d+)(?:\s*[—–-]\s*|\.[ \t]*|\s+)(.*)$/, split: /^## (?:§)?(\d+)(?!\d)/ },
};
export const fileOf = (n) => `${String(n).padStart(4, '0')}.md`;
const ITEM_FILE = /^(\d{4})\.md$/;
export const BEGIN = '<!-- item-index:begin — GENERATED by tools/item-docs.mjs --write; never edit between the markers -->';
export const END = '<!-- item-index:end -->';

// A source: the working tree, or a git ref.
export const treeSource = (root = ROOT) => ({
  read: (p) => (existsSync(join(root, p)) ? readFileSync(join(root, p), 'utf8') : null),
  list: (d) => (existsSync(join(root, d)) ? readdirSync(join(root, d)) : null),
});
export const refSource = (ref, root = ROOT) => {
  const git = (...a) => { try { return execFileSync('git', a, { cwd: root, encoding: 'utf8', maxBuffer: 1 << 28 }); } catch { return null; } };
  return {
    read: (p) => git('show', `${ref}:${p}`),
    list: (d) => { const t = git('ls-tree', '--name-only', `${ref}`, `${d}/`); return t === null || !t.trim() ? null : t.split('\n').filter(Boolean).map((f) => f.slice(d.length + 1)); },
  };
};

// The item files' numbers, ascending; null when the source has no directory.
export function itemNumbers(ns, src) {
  const names = src.list(ITEM_DOCS[ns].dir);
  if (!names) return null;
  return names.map((f) => ITEM_FILE.exec(f)).filter(Boolean).map((m) => Number(m[1])).sort((a, b) => a - b);
}
// The document's text for heading parsers: the items concatenated, or the
// legacy single file on a ref that predates the split. null when neither exists.
export function itemText(ns, src) {
  const cfg = ITEM_DOCS[ns], nums = itemNumbers(ns, src);
  if (nums) return nums.map((n) => src.read(`${cfg.dir}/${fileOf(n)}`) ?? '').join('\n');
  return src.read(cfg.index);
}

// ---- the index -------------------------------------------------------------
const STATE = /\s*[—–-]\s*((?:[A-Z][A-Z0-9 ,]*|PART DONE|MOSTLY CLOSED)(?:\s*\([^)]*\))?)\s*$/;
const LEAD_STATE = /^((?:MOSTLY |PARTLY )?CLOSED|DONE)\b\s*(?:\([^)]*\))?\s*[—–:-]?\s*/;
const cell = (s) => s.replace(/\|/g, '\\|');
function todoRow(n, text) {
  const h = text.split('\n').find((l) => ITEM_DOCS.TODO.heading.test(l)) || '';
  let title = (ITEM_DOCS.TODO.heading.exec(h) || [])[2] || '';
  let state = 'OPEN';
  const lead = LEAD_STATE.exec(title);
  if (lead) { state = lead[0].replace(/[—–:-]?\s*$/, '').trim(); title = title.slice(lead[0].length); }
  const tail = STATE.exec(title);
  if (tail && /CLOSED|DONE|FIXED|RETIRED|WITHDRAWN|SUPERSEDED|DELETED|STEP|TIER|PART|MOSTLY|LANDED|BUILT/.test(tail[1])) { state = tail[1]; title = title.slice(0, tail.index); }
  return { n, state, title: title.trim() };
}
function builtRow(n, text) {
  const hs = text.split('\n').filter((l) => ITEM_DOCS.BUILT.split.test(l));
  const title = (hs[0] || '').replace(/^## (?:§)?\d+(?:\s*[—–-]\s*|\.[ \t]*|,\s*|\s+)?/, '').trim();
  return { n, title, parts: hs.length };
}
// The hand-written status table (docs/todo/STATUS.md) is the second source of
// an item's state: the heading convention says a closed item says so in its
// heading, and some closed in their text without it. Where the heading is
// silent the table's state is shown and MARKED, so the index never claims more
// than one of the two sources does.
const statusTable = (src) => {
  const m = new Map();
  for (const l of (src.read('docs/todo/STATUS.md') || '').split('\n')) { const r = /^\| (\d+) \| ([^|]+) \|/.exec(l); if (r) m.set(Number(r[1]), r[2].trim()); }
  return m;
};
export function renderIndex(ns, src) {
  const cfg = ITEM_DOCS[ns], nums = itemNumbers(ns, src) || [];
  const rows = nums.map((n) => (ns === 'TODO' ? todoRow : builtRow)(n, src.read(`${cfg.dir}/${fileOf(n)}`) ?? ''));
  if (ns === 'TODO') {
    const st = statusTable(src);
    for (const r of rows) if (r.state === 'OPEN' && st.has(r.n) && st.get(r.n) !== 'OPEN') { r.state = `${st.get(r.n)} †`; r.fromTable = true; }
  }
  const link = (n) => `[${ns === 'TODO' ? n : `§${n}`}](${ns === 'TODO' ? 'docs/todo' : 'built'}/${fileOf(n)})`;
  const out = [BEGIN, ''];
  if (ns === 'TODO') {
    const open = rows.filter((r) => !/CLOSED|DONE|RETIRED|WITHDRAWN|SUPERSEDED|DELETED/.test(r.state) || /PART|MOSTLY|STEP|TIER/.test(r.state));
    const shut = rows.filter((r) => !open.includes(r));
    out.push(`${rows.length} items: ${open.length} open or part done, ${shut.length} closed. Newest first. `
      + 'State is read from each heading; † marks one read from [the status table](docs/todo/STATUS.md) because the heading does not say.', '');
    for (const [head, list] of [['Open, or part done', open], ['Closed', shut]]) {
      out.push(`### ${head}`, '', '| Item | State | Title |', '|---|---|---|');
      for (const r of list.slice().reverse()) out.push(`| ${link(r.n)} | ${cell(r.state)} | ${cell(r.title)} |`);
      out.push('');
    }
  } else {
    out.push(`${rows.length} sections. Newest first.`, '', '| § | Title | Parts |', '|---|---|---|');
    for (const r of rows.slice().reverse()) out.push(`| ${link(r.n)} | ${cell(r.title)} | ${r.parts} |`);
    out.push('');
  }
  out.push(END);
  return out.join('\n');
}
// The index file with its generated block replaced.
export function withIndex(ns, src) {
  const cur = src.read(ITEM_DOCS[ns].index) || '';
  const a = cur.indexOf(BEGIN), b = cur.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${ITEM_DOCS[ns].index}: the index markers are missing`);
  return cur.slice(0, a) + renderIndex(ns, src) + cur.slice(b + END.length);
}

// ---- the integrity check ---------------------------------------------------
// What a reader relies on: every item file holds its own number's heading and
// no other number's, the index file holds no item heading at all (so a parser
// over itemText never counts it), and the generated block is current.
export function checkDocs(src = treeSource()) {
  const fail = [];
  for (const [ns, cfg] of Object.entries(ITEM_DOCS)) {
    const nums = itemNumbers(ns, src);
    if (!nums) { fail.push(`${cfg.dir}/ is missing`); continue; }
    const re = cfg.split || cfg.heading;
    for (const n of nums) {
      const t = src.read(`${cfg.dir}/${fileOf(n)}`) ?? '';
      const seen = t.split('\n').map((l) => re.exec(l)).filter(Boolean).map((m) => Number(m[1]));
      if (!seen.length) fail.push(`${cfg.dir}/${fileOf(n)}: no heading for ${n}`);
      if (!t.startsWith('## ')) fail.push(`${cfg.dir}/${fileOf(n)}: does not open on its heading`);
      for (const k of seen) if (k !== n) fail.push(`${cfg.dir}/${fileOf(n)}: carries a heading for ${k}`);
    }
    const idx = src.read(cfg.index) || '';
    for (const l of idx.split('\n')) if (re.test(l)) fail.push(`${cfg.index}: carries an item heading ("${l.slice(0, 60)}") — items live in ${cfg.dir}/`);
    try { if (withIndex(ns, src) !== idx) fail.push(`${cfg.index}: the index is stale — run node tools/item-docs.mjs --write`); }
    catch (e) { fail.push(e.message); }
  }
  return fail;
}

// ---- the one-time split ----------------------------------------------------
// Each chunk runs from a numbered heading to the next numbered heading; an
// unnumbered `##` stays with the item above it, except the named sections
// below, which are not items and get their own file. A trailing `---` rule
// was a separator between sections in the single file and is dropped.
function chunks(text, re, named = []) {
  const lines = text.split('\n'), out = [];
  let cur = { key: 'head', lines: [] };
  for (const l of lines) {
    const m = re.exec(l), nm = named.find((x) => x.test.test(l));
    if (m || nm) { out.push(cur); cur = { key: m ? Number(m[1]) : nm.file, lines: [l] }; } else cur.lines.push(l);
  }
  out.push(cur);
  for (const c of out) { while (c.lines.length && /^\s*(---)?\s*$/.test(c.lines[c.lines.length - 1])) c.lines.pop(); }
  return out;
}
// An in-document anchor `(#32-closed-…)` points into another item's file now.
const relink = (s, base) => s.replace(/\]\(#(\d+)(-[^)]*)\)/g, (_, n, slug) => `](${base}${fileOf(Number(n))}#${n}${slug})`);
function split() {
  for (const cfg of Object.values(ITEM_DOCS)) if (existsSync(join(ROOT, cfg.dir))) throw new Error(`${cfg.dir}/ exists — the split has been done`);
  const write = (p, s) => { mkdirSync(dirname(join(ROOT, p)), { recursive: true }); writeFileSync(join(ROOT, p), s.endsWith('\n') ? s : s + '\n'); };
  const report = {};
  for (const [ns, cfg] of Object.entries(ITEM_DOCS)) {
    const text = readFileSync(join(ROOT, cfg.index), 'utf8');
    const named = ns === 'TODO' ? [{ test: /^## Status index\s*$/, file: 'STATUS.md' }, { test: /^## Recently closed\s*$/, file: 'recently-closed.md' }] : [];
    const parts = chunks(text, cfg.split || cfg.heading, named);
    const byNum = new Map(), files = new Map();
    let head = '';
    for (const c of parts) {
      const body = c.lines.join('\n');
      if (c.key === 'head') head = body;
      else if (typeof c.key === 'number') { if (!byNum.has(c.key)) byNum.set(c.key, []); byNum.get(c.key).push(body); }
      else files.set(c.key, body);
    }
    for (const [n, bodies] of byNum) write(`${cfg.dir}/${fileOf(n)}`, relink(bodies.join('\n\n---\n\n'), ''));
    for (const [f, body] of files) write(`${cfg.dir}/${f}`, relink(body, ''));
    report[ns] = { items: byNum.size, repeated: [...byNum].filter(([, b]) => b.length > 1).length, named: [...files.keys()], headChars: head.length, bytes: text.length };
    writeFileSync(join(ROOT, `${cfg.index}.head`), head);   // the old head, for the hand-written index head to be built from
  }
  return report;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const arg = process.argv[2];
  if (arg === '--split') { console.log(JSON.stringify(split(), null, 1)); }
  else if (arg === '--write') {
    for (const [ns, cfg] of Object.entries(ITEM_DOCS)) writeFileSync(join(ROOT, cfg.index), withIndex(ns, treeSource()));
    console.log('wrote TODO.md and docs/BUILT.md indexes');
  } else if (arg === '--check') {
    const fail = checkDocs();
    for (const f of fail) console.error(`FAIL  ${f}`);
    if (fail.length) process.exit(1);
    const t = itemNumbers('TODO', treeSource()).length, b = itemNumbers('BUILT', treeSource()).length;
    console.log(`PASS  ${t} TODO items and ${b} BUILT sections, one file each; both indexes current, neither carries an item heading`);
  } else { console.error('usage: node tools/item-docs.mjs --check | --write | --split'); process.exit(2); }
}
