#!/usr/bin/env node
// Writes src/technic-bricklink.js: the SUBSET of BrickLink's catalogue downloads
// (Parts, Colors, Codes — https://www.bricklink.com/catalogDownload.asp, tab-
// delimited) that the parts list needs, so the purchase ids and colour ids are
// READ from BrickLink and never typed (BUILT §300's rule). The three whole files
// are 14 MB and are not committed; this keeps one row per LDraw id the builds
// place, one row per LDraw colour the role table uses, and the element codes
// those pairs have. `--check` re-derives the file from the same three downloads
// and fails if it differs; with no downloads it only reads the committed file
// back and checks its shape.
//
//   node tools/bricklink-subset.mjs --write --parts P --colors C --codes K --date YYYY-MM-DD
//   node tools/bricklink-subset.mjs --check [--parts P --colors C --codes K]
//
// The LDraw ids come from the PART_TABLE keys in src/technic-bom.js and the
// colour codes from LDRAW_COLOUR in src/technic-ldraw.js, so a part or colour a
// build starts placing is absent here until the file is rewritten, and the BOM
// probe fails on it.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { PART_IDS } from '../src/technic-bom-ids.js';
import { LDRAW_COLOUR } from '../src/technic-ldraw.js';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i < 0 ? null : args[i + 1]; };
const OUT = new URL('../src/technic-bricklink.js', import.meta.url).pathname;
const table = (path) => readFileSync(path, 'utf8').split(/\r?\n/).map((l) => l.split('\t'));

// BrickLink's name for each LDraw colour code the role table uses. LDraw and BrickLink
// name these ten alike; the mapping is by NAME against Colors.txt, and a name that
// is not there fails (never a guess).
const LDRAW_NAME = { 0: 'Black', 1: 'Blue', 2: 'Green', 4: 'Red', 14: 'Yellow', 15: 'White', 19: 'Tan', 25: 'Orange',
  71: 'Light Bluish Gray', 72: 'Dark Bluish Gray' };

export function derive({ parts, colors, codes, date }) {
  const P = table(parts).slice(1).filter((r) => r.length >= 4 && r[2]);
  const number = new Map(), alt = new Map();
  for (const r of P) {
    number.set(r[2].toLowerCase(), r);
    for (const a of (r[4] ?? '').split(',').map((s) => s.trim()).filter(Boolean)) if (!alt.has(a.toLowerCase())) alt.set(a.toLowerCase(), r);
  }
  const outParts = {};
  for (const id of PART_IDS) {
    // BrickLink does not list every LDraw mould-variant letter (3023b, 32123a, 4032a,
    // 4185a): the base id is the item (as an item number or an alternate of one), and
    // `via` says so, so the page can flag it. Anything else not found fails.
    const base = /^\d+[a-z]$/i.test(id) ? id.slice(0, -1).toLowerCase() : null;
    const r = number.get(id.toLowerCase()), a = alt.get(id.toLowerCase());
    const rb = !r && !a && base ? number.get(base) : null, ab = !r && !a && !rb && base ? alt.get(base) : null;
    const hit = r ?? a ?? rb ?? ab;
    const via = r ? 'number' : a ? 'alternate' : rb ? 'base number' : 'base alternate';
    if (!hit) throw new Error(`bricklink-subset: LDraw id ${id} is neither an item number nor an alternate item number in Parts`);
    outParts[id] = { number: hit[2], name: hit[3], category: hit[1], via, alternates: (hit[4] ?? '').split(',').map((s) => s.trim()).filter(Boolean) };
  }
  const C = table(colors).slice(1).filter((r) => r.length >= 3 && /^\d+$/.test(r[0]));
  const outColours = {};
  for (const code of Object.keys(LDRAW_NAME)) {
    const r = C.find((x) => x[1] === LDRAW_NAME[code]);
    if (!r) throw new Error(`bricklink-subset: no BrickLink colour named ${LDRAW_NAME[code]}`);
    outColours[code] = { id: Number(r[0]), name: r[1], rgb: r[2] };
  }
  for (const code of new Set(Object.values(LDRAW_COLOUR))) if (!outColours[code]) throw new Error(`bricklink-subset: LDRAW_COLOUR uses colour ${code} with no BrickLink name here`);
  const K = table(codes).slice(1).filter((r) => r.length >= 3 && r[0]);
  const want = new Set(Object.values(outParts).map((p) => p.number.toLowerCase()));
  const byName = Object.fromEntries(Object.entries(outColours).map(([c, v]) => [v.name, c]));
  const elements = {};
  for (const r of K) {
    if (!want.has(r[0].toLowerCase()) || byName[r[1]] === undefined) continue;
    ((elements[r[0]] ??= {})[byName[r[1]]] ??= []).push(r[2]);
  }
  for (const n of Object.keys(elements)) for (const c of Object.keys(elements[n])) elements[n][c].sort();
  return { source: { site: 'BrickLink Catalog Download (bricklink.com/catalogDownload.asp), tab-delimited Parts, Colors and Codes', date }, parts: outParts, colours: outColours, elements };
}

const text = (d) => `// GENERATED by tools/bricklink-subset.mjs — do not edit. The part of BrickLink's catalogue
// downloads (Parts, Colors, Codes) that the LEGO parts list uses, downloaded ${d.source.date}
// by the owner from bricklink.com. A row per LDraw id the builds place (its BrickLink
// item number, name and category, and whether the LDraw id IS the item number or one
// of its alternate numbers), a row per LDraw colour the role table uses (BrickLink's
// colour id, name and RGB, matched by name), and the element codes each placed part
// has in those colours. A (part, colour) with no element here is not listed by
// BrickLink in that colour. BrickLink is the source; the repo stores the subset.
export const BRICKLINK = ${JSON.stringify(d, null, 1)};
`;

if (args.includes('--write')) {
  const d = derive({ parts: flag('--parts'), colors: flag('--colors'), codes: flag('--codes'), date: flag('--date') });
  writeFileSync(OUT, text(d));
  console.log(`wrote ${OUT}: ${Object.keys(d.parts).length} parts, ${Object.keys(d.colours).length} colours, ${Object.keys(d.elements).length} items with elements`);
} else if (args.includes('--check')) {
  const { BRICKLINK } = await import('../src/technic-bricklink.js');
  let bad = 0;
  const fail = (m) => { console.log('  FAIL ' + m); bad++; };
  for (const id of PART_IDS) if (!BRICKLINK.parts[id]) fail(`no BrickLink row for LDraw id ${id}`);
  for (const id of Object.keys(BRICKLINK.parts)) if (!PART_IDS.includes(id)) fail(`BrickLink row ${id} is placed by no build (stale)`);
  for (const c of new Set(Object.values(LDRAW_COLOUR))) if (!BRICKLINK.colours[c]) fail(`no BrickLink colour for LDraw ${c}`);
  if (flag('--parts')) {
    const d = derive({ parts: flag('--parts'), colors: flag('--colors'), codes: flag('--codes'), date: BRICKLINK.source.date });
    if (JSON.stringify(d) !== JSON.stringify(BRICKLINK)) fail('the committed subset differs from the downloads');
  }
  console.log(bad ? `bricklink subset: ${bad} failure(s)` : `bricklink subset OK — ${PART_IDS.length} parts, ${Object.keys(BRICKLINK.colours).length} colours${flag('--parts') ? ', re-derived from the downloads' : ''}`);
  process.exit(bad ? 1 : 0);
} else { console.log('usage: --write --parts P --colors C --codes K --date D | --check [--parts P --colors C --codes K]'); process.exit(2); }
