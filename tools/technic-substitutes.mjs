#!/usr/bin/env node
// Writes src/technic-substitutes-verdicts.js (BUILT §309): the model's verdict on every
// SUBSTITUTE candidate src/technic-rebrickable.js names for a placed LEGO part — passed,
// failed (with the judge that failed) or not judged (with why). Generated, never typed:
// each verdict is what tools/technic-substitutes-judge.mjs measured by running the
// model's own judges with the candidate's geometry swapped in (tools/technic-pack.mjs).
// tools/probe-technic-substitutes.mjs re-judges the file and fails on any difference.
//
//   node tools/technic-substitutes.mjs --write [--jobs 3] [--cache FILE]   about 90 minutes on 4 cores
//
// Needs tools/data/technic-candidates.mpd (`node tools/ldraw-vendor.mjs --candidates`).
import { readFileSync, writeFileSync, appendFileSync, existsSync } from 'node:fs';
import { parseLibrary } from '../src/ldraw.js';
import { MAIN_PACK, CANDIDATE_PACK } from './technic-pack.mjs';
import { judgeAll } from './technic-substitutes-judge.mjs';
import { REBRICKABLE } from '../src/technic-rebrickable.js';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i < 0 ? null : args[i + 1]; };
const OUT = new URL('../src/technic-substitutes-verdicts.js', import.meta.url).pathname;
if (!args.includes('--write')) { console.log('usage: --write [--jobs N]'); process.exit(2); }

const candText = readFileSync(CANDIDATE_PACK, 'utf8');
const libs = { main: parseLibrary(readFileSync(MAIN_PACK, 'utf8')), cand: parseLibrary(candText) };
const t0 = Date.now();
// --cache FILE: one JSON line per judge run measured, read back on a restart (a scratch file for one session's tree)
const cacheFile = flag('--cache'), cache = new Map();
if (cacheFile && existsSync(cacheFile)) for (const l of readFileSync(cacheFile, 'utf8').split('\n').filter(Boolean)) { const { key, res } = JSON.parse(l); cache.set(key, res); }
const verdicts = await judgeAll(libs, { jobs: Number(flag('--jobs') ?? 3), log: (s) => console.log(s), cache,
  onResult: (key, res) => { if (cacheFile) appendFileSync(cacheFile, JSON.stringify({ key, res }) + '\n'); } });
const missing = /^0 Missing: (.*)$/m.exec(candText)?.[1] ?? '-';
const d = { source: { rebrickable: REBRICKABLE.source.date, bricklink: REBRICKABLE.source.bricklink, candidatesPack: 'tools/data/technic-candidates.mpd', missingFromLibrary: missing === '-' ? [] : missing.split(' ') }, verdicts };
writeFileSync(OUT, `// GENERATED by tools/technic-substitutes.mjs — do not edit. BUILT §309: the model's verdict on
// every substitute candidate src/technic-rebrickable.js names. A candidate PASSES only when every
// judge the model already has passes with its geometry in place of the placed part's and nothing
// else changed (tools/technic-substitutes-judge.mjs lists them); \`judge\` names the first that
// failed, or why it was not judged. MODELLED, not built: a pass says the model's judges accept the
// part's geometry, not that anyone has built it. tools/probe-technic-substitutes.mjs re-judges this.
export const SUBSTITUTE_VERDICTS = ${JSON.stringify(d, null, 1)};
`);
const all = Object.values(verdicts).flat(), by = (s) => all.filter((v) => v.status === s).length;
console.log(`wrote ${OUT}: ${all.length} candidates — ${by('pass')} pass, ${by('fail')} fail, ${by('not judged')} not judged, ${by('skip')} skipped (${Math.round((Date.now() - t0) / 1000)} s)`);
