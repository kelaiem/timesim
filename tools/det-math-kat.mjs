#!/usr/bin/env node
// §338 landing 2 — WRITES src/det-math-kat.js: the known answers of the
// installed deterministic maths (src/det-math.js' knownAnswers), recorded.
//
//   node tools/det-math-kat.mjs            write the table
//   node tools/det-math-kat.mjs --check    fail if this engine does not reproduce it
//
// GENERATED, NEVER EDITED. Two sizes: BOOT (the few hundred inputs per function
// the page and the native host check at every boot, a few ms) and FULL (many
// thousands, which this --check and tools/probe-338-det-math.mjs run). The
// table is what the library computes, written down. Its value is that every
// host is held to the SAME numbers: an engine whose arithmetic does not
// reproduce them, or a vendored library that moved without this being re-run,
// is caught by name, function by function.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { knownAnswers } from '../src/det-math.js';

const ENGINE = typeof Bun !== 'undefined' ? `Bun ${Bun.version} (JavaScriptCore)` : `Node ${process.version} (V8 ${process.versions.v8})`;

export const BOOT_N = 256, FULL_N = 20000;
const OUT = fileURLToPath(new URL('../src/det-math-kat.js', import.meta.url));
const boot = knownAnswers(BOOT_N), full = knownAnswers(FULL_N);
const text = `// GENERATED by tools/det-math-kat.mjs (§338 landing 2). DO NOT EDIT: re-run the tool.
//
// src/det-math.js' knownAnswers(n), recorded: per installed function, the FNV
// hash of its results' bits (NaN canonical) over a fixed input set. The page
// and the native host check BOOT at every boot; the tool's --check and
// tools/probe-338-det-math.mjs check FULL.
export const KAT_BOOT_N = ${BOOT_N};
export const KAT_BOOT = Object.freeze(${JSON.stringify(boot, null, 2)});
export const KAT_FULL_N = ${FULL_N};
export const KAT_FULL = Object.freeze(${JSON.stringify(full, null, 2)});
`;
if (process.argv.includes('--check')) {
  const cur = readFileSync(OUT, 'utf8');
  if (cur !== text) {
    const { KAT_BOOT, KAT_FULL } = await import('../src/det-math-kat.js');
    const moved = Object.keys(full).filter((k) => KAT_FULL[k] !== full[k] || KAT_BOOT[k] !== boot[k]);
    console.error(`det-math-kat --check FAILED on ${ENGINE}: ${moved.length ? moved.join(', ') : 'the file\'s text'} moved — the library or this engine's arithmetic differs from the recorded table`);
    process.exit(1);
  }
  console.log(`det-math-kat --check OK — ${Object.keys(full).length} functions reproduce the table (${FULL_N + 23} inputs each) on ${ENGINE}`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote src/det-math-kat.js — ${Object.keys(full).length} functions`);
}
