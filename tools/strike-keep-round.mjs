// Generate src/strike-keep-round.js — each round alarm build's drawn hammer head as the keep-out its pillar scan yields to (TODO 290).
//   node tools/strike-keep-round.mjs --write    boot every round alarm spec that must boot clean, read __clock.roundStrikeKeep.measured, write the table
//   node tools/strike-keep-round.mjs --check    boot them and fail if the table is not what the builds measure (and say why)
// TODO 272's idiom for the round case: the pillars are sited ~13,000 lines before the hammer is cut, so the strike group's
// footprint is DECLARED ahead of the scan by a generated table and re-measured by the alarm block, which warns when the two
// part. The keep is the hull of the head's plan footprint at its INTENDED length (the radial room at rest) and section over
// the whole draw, so it does not depend on where the pillars stand, and one write is a fixed point. The check below boots
// twice when the table moves: the build sited on the new table must measure the same keep.
import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bootForm } from './boot-form.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FILE = join(ROOT, 'src', 'strike-keep-round.js');
const mode = process.argv.includes('--write') ? 'write' : process.argv.includes('--check') ? 'check' : null;
if (!mode) { console.log('usage: strike-keep-round.mjs --write | --check'); process.exit(2); }

const EXPR = 'window.__clock.roundStrikeKeep';
// §325 landing 16 — ONE ROW PER ROUND ALARM SPEC THAT MUST BOOT CLEAN: the battery's silent spec points (tools/ci-battery.mjs
// SPEC_POINTS, expect 'silent') that build the round case with the alarm. They key by the gong's spec key, so `reconf=1`,
// `frame=pillars`, `arrest=stop-iron` and the route points share a row with the build they vary. A spec with no row keeps
// the frame law (ALARM_HEAD_DIMS) as its tripwire, and may warn: the 'any' points are allowed to.
const QUERIES = ['', 'arrangement=designed', 'arrangement=designed&studr=7.595', 'arrangement=designed&studr=4.71', 'arrangement=designed&studr=7.1175'];
const render = (rows) => `// GENERATED by tools/strike-keep-round.mjs — never edit; re-run it (--check re-derives).
// TODO 290 / §325 landing 16: each round alarm build's drawn hammer head (at its intended length and section, over the whole
// draw), the keep its pillar scan yields to, one row per spec key.
export const STRIKE_KEEP_ROUND = Object.freeze({
${rows.map((k) => `  ${JSON.stringify(k.specKey)}: Object.freeze({ L: ${k.L.toFixed(4)}, H: ${k.H.toFixed(4)}, hull: Object.freeze(${JSON.stringify(k.hull)}) }),`).join('\n')}
});
`;

const bootAll = async () => {
  const rows = [], warns = [], declared = [];
  for (const q of QUERIES) {
    const r = await bootForm(q, EXPR);
    if (r.bootError) throw new Error(`?${q} did not boot: ${r.bootError}`);
    if (!r.extra?.measured) throw new Error(`?${q} measured no round strike keep (no alarm, or a form case?)`);
    if (!rows.some((k) => k.specKey === r.extra.measured.specKey)) rows.push(r.extra.measured);
    declared.push(!!r.extra.declared);
    for (const w of r.warnings) warns.push(`?${q}: ${w}`);
  }
  return { rows, warns, declared };
};

let r = await bootAll();
const want = render(r.rows), have = await readFile(FILE, 'utf8');
if (mode === 'check') {
  if (have !== want) { console.log('FAIL: src/strike-keep-round.js is not what the builds measure — run --write'); process.exit(1); }
  if (r.declared.some((d) => !d)) { console.log('FAIL: the table is current but a build did not read its row (spec key?)'); process.exit(1); }
  console.log(`PASS: src/strike-keep-round.js re-derives (${r.rows.length} rows over ${QUERIES.length} builds), and every build reads its row`);
} else {
  if (have === want) { console.log('unchanged'); process.exit(0); }
  await writeFile(FILE, want);
  // the fixed point: builds sited on the table just written must measure the same keeps
  r = await bootAll();
  if (render(r.rows) !== want) { console.log('FAIL: a build sited on the new keep measures a different one — the station depends on the frame'); process.exit(1); }
  console.log(`wrote src/strike-keep-round.js (${r.rows.length} rows); builds sited on it measure it back`);
  for (const w of r.warns) console.log('  boot: ' + w);
}
