// Generate src/strike-keep-round.js — the round build's drawn hammer head as the keep-out its pillar scan yields to (TODO 290).
//   node tools/strike-keep-round.mjs --write    boot the default round build, read __clock.roundStrikeKeep.measured, write the table
//   node tools/strike-keep-round.mjs --check    boot it and fail if the table is not what the build measures (and say why)
// TODO 272's idiom for the round case: the pillars are sited ~13,000 lines before the hammer is cut, so the strike group's
// footprint is DECLARED ahead of the scan by a generated table and re-measured by the alarm block, which warns when the two
// part. The keep is the hull of the head's plan footprint at its INTENDED length (the radial room at rest) and section over
// the whole draw, so it does not depend on where the pillars stand, and one write is a fixed point. The check below boots
// twice when the table moves: the build sited on the new table must measure the same keep.
import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bootForm } from './boot-form.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FILE = join(ROOT, 'src', 'strike-keep-round.js');
const mode = process.argv.includes('--write') ? 'write' : process.argv.includes('--check') ? 'check' : null;
if (!mode) { console.log('usage: strike-keep-round.mjs --write | --check'); process.exit(2); }

const EXPR = 'window.__clock.roundStrikeKeep';
const render = (k) => `// GENERATED by tools/strike-keep-round.mjs — never edit; re-run it (--check re-derives).
// TODO 290: the round build's drawn hammer head (length ${k.L.toFixed(4)} u, section ${k.H.toFixed(4)} u, over the whole draw),
// the keep its pillar scan yields to. Read only under this spec key.
export const STRIKE_KEEP_ROUND = Object.freeze({
  specKey: ${JSON.stringify(k.specKey)},
  hull: Object.freeze(${JSON.stringify(k.hull)}),
});
`;

const boot = async () => {
  const r = await bootForm('', EXPR);
  if (r.bootError) throw new Error(`the default build did not boot: ${r.bootError}`);
  if (!r.extra?.measured) throw new Error('the default build measured no round strike keep (no alarm, or a form case?)');
  return r;
};

let r = await boot();
const want = render(r.extra.measured), have = await readFile(FILE, 'utf8');
if (mode === 'check') {
  if (have !== want) { console.log('FAIL: src/strike-keep-round.js is not what the default build measures — run --write'); process.exit(1); }
  if (!r.extra.declared) { console.log('FAIL: the table is current but the build did not read it (spec key?)'); process.exit(1); }
  console.log(`PASS: src/strike-keep-round.js re-derives (${r.extra.measured.hull.length}-point hull), and the build reads it`);
} else {
  if (have === want) { console.log('unchanged'); process.exit(0); }
  await writeFile(FILE, want);
  // the fixed point: a build sited on the table it just wrote must measure the same keep
  r = await boot();
  const again = render(r.extra.measured);
  if (again !== want) { console.log('FAIL: a build sited on the new keep measures a different one — the station depends on the frame'); process.exit(1); }
  console.log(`wrote src/strike-keep-round.js (${r.extra.measured.hull.length}-point hull); a build sited on it measures it back`);
  for (const w of r.warnings) console.log('  boot: ' + w);
}
