#!/usr/bin/env node
// TODO 298 — WRITE OR CHECK src/form-fits.js, the fit each ALARM-FREE box form case is cut to. ACCEPTANCE (--check exits
// non-zero on drift).
//
// A box form case (rect, cushion, tonneau, fitted) is cut to a fit of the counted metal (layout.js formShapeOf over the
// shape's bounds, and the fitted kind's k and tau). The alarm build carries that fit in its gong seat's row
// (tools/gong-seats.mjs, main.js FORM_SEAT_FIT), the free case in src/free-outlines.js. Nothing carried it for a build
// without the alarm, so every ?alarm=0 box kind was cut to the solvers' formPlate, the first boot's guess: on the fitted
// case the counted metal stood 1.611 u outside its outline and the case middle ran through the setting lever. This closes
// that loop:
//
//   1. boot the kind (the committed row, if any, as ?formrect=; an explicit fit always wins, so no table is served) and
//      read the fit the build measured off __clock.formFootprint.rect, and its key off __clock.formFit.key;
//   2. boot again at that fit, until the fit the build measures is the fit it was cut to (a FIXED POINT: the metal may
//      follow the outline — a pillar seated on the plate — so one boot's fit is not yet the answer), at most ROUNDS;
//   3. write every kind's row.
//
// --check boots each kind BARE (no ?formrect=) and holds two things: the build read its fit from this table
// (formFit.from === 'table'), and the fit it measures there is the row (so the row is still its own fixed point on this
// tree). Either failing exits non-zero.
//
//   node tools/form-fits.mjs --write [--spec 'k=v&…'] [kind …]   solve the default alarm-free movement's rows (or the spec's)
//   node tools/form-fits.mjs --check [--spec …] [kind …]          re-derive and compare with the committed file
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bootMany } from './boot-pool.mjs';
import { FORM_KINDS } from '../src/layout.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..'), OUT = join(ROOT, 'src/form-fits.js');
const ARGS = process.argv.slice(2), WRITE = ARGS.includes('--write'), CHECK = ARGS.includes('--check');
const SPECQ = ARGS.includes('--spec') ? ARGS[ARGS.indexOf('--spec') + 1] : null;
const KINDS = ARGS.filter((a, i) => !a.startsWith('--') && ARGS[i - 1] !== '--spec');
if (WRITE === CHECK) { console.error('usage: node tools/form-fits.mjs --write | --check [--spec k=v&…] [kind …]'); process.exit(2); }
for (const k of KINDS) if (!FORM_KINDS.includes(k)) { console.error(`'${k}' is not one of FORM_KINDS (${FORM_KINDS.join(', ')})`); process.exit(2); }
const kinds = KINDS.length ? KINDS : [...FORM_KINDS];
const ROUNDS = 4;

const { FORM_FITS: COMMITTED } = await import(`${join(ROOT, 'src/form-fits.js')}?t=${Date.now()}`);
const fileText = (rows) => `// GENERATED by tools/form-fits.mjs — never edit by hand; re-run the tool (--check re-derives it).
//
// TODO 298: per alarm-free box form case (the configuration key of its spec without the hands, the fit and the seat),
// the fit the case is cut to, as ?formrect= would carry it: the shape's bounds (xMin, xMax, yMin, yMax) and, for the
// fitted kind, its side curvature k and apex height tau. Each is its own fixed point: booted at it, the build fits the
// counted metal to the same numbers.
export const FORM_FITS = Object.freeze({
${Object.keys(rows).sort().map((k) => ` ${JSON.stringify(k)}: Object.freeze(${JSON.stringify(rows[k])}),`).join('\n')}
});
`;
const EXPR = `({ fit: window.__clock.formFit, rect: Array.from(window.__clock.formFootprint?.rect ?? []).map(Number),
  margin: window.__clock.formFootprint?.margin ?? null })`;
const base = (kind) => ['alarm=0', `case=${kind}`, SPECQ].filter(Boolean).join('&');
const same = (a, b) => a.length === b.length && a.every((v, i) => v === b[i]);
const bootOne = async (q) => {
  const [r] = await bootMany([q], EXPR, { concurrency: 1 });
  if (r.bootError || r.unknownKeys?.length || !r.extra) throw new Error(`${q}: ${r.bootError ?? `unknown keys ${r.unknownKeys}`}`);
  return r.extra;
};

if (CHECK) {
  const rs = await bootMany(kinds.map(base), EXPR);
  let failed = false;
  rs.forEach((r, i) => {
    const kind = kinds[i];
    if (r.bootError || !r.extra) { console.log(`FAIL ${kind}: ${r.bootError ?? 'no reading'}`); failed = true; return; }
    const { fit, rect } = r.extra, row = COMMITTED[fit.key];
    if (fit.from !== 'table' || !row) { console.log(`FAIL ${kind}: cut to ${fit.from}, not this table (no row for ${fit.key})`); failed = true; return; }
    if (!same(rect, row)) { console.log(`FAIL ${kind}: the row is no longer its own fixed point — cut to ${row.join(',')}, the metal fits ${rect.join(',')}`); failed = true; return; }
    console.log(`PASS ${kind}: cut to its own fit ${row.join(',')}`);
  });
  process.exit(failed ? 1 : 0);
}

const rows = { ...COMMITTED };
const solve = async (kind) => {
  let r = await bootOne(base(kind)), cutTo = null;
  const key = r.fit.key;
  if (COMMITTED[key]) { cutTo = [...COMMITTED[key]]; r = await bootOne(`${base(kind)}&formrect=${cutTo.join(',')}`); }
  for (let round = 1; round <= ROUNDS; round++) {
    if (cutTo && same(r.rect, cutTo)) return { kind, key, row: cutTo, round };
    if (!r.rect.length) throw new Error(`${kind}: the build measured no fit`);
    cutTo = r.rect;
    console.log(`${kind}: round ${round}, cut to ${cutTo.join(',')}`);
    r = await bootOne(`${base(kind)}&formrect=${cutTo.join(',')}`);
    if (r.fit.key !== key) throw new Error(`${kind}: the key moved between rounds (${key} → ${r.fit.key})`);
  }
  throw new Error(`${kind}: no fixed point in ${ROUNDS} rounds (last cut ${cutTo.join(',')}, measured ${r.rect.join(',')})`);
};
let failed = false;
for (const kind of kinds) {
  try { const s = await solve(kind); rows[s.key] = s.row; console.log(`${kind}: settled at ${s.row.join(',')}`); }
  catch (e) { console.error(`FAIL ${e.message}`); failed = true; }
}
writeFileSync(OUT, fileText(rows));
console.log(`wrote ${OUT}`);
process.exit(failed ? 1 : 0);
